package app

import "time"

// readoutMoved 报「进度条上那个读数变了没有」。
//
// # 它是给谁用的
//
// `tick` 每一拍都会读一次位置（那是播放器的时钟：位置采样、切歌淡出、播放
// 记录、上次听到哪儿落盘，全都要那一拍）。但**界面不该跟着每一拍重建**——
// 屏幕上真在变的东西只有进度条的读数，而它一秒才变一次。
//
// 所以 tick 拿这一句决定「这一拍要不要叫醒窗口」：上一次报出去的位置和这一拍
// 读到的位置，**截断到秒之后**变了才叫。20Hz → 约 1Hz。
//
// # 为什么是截断到秒
//
// 判据必须和界面画出来的那个数**同一个口径**：`internal/ui/playbar.go` 的
// `clockOrDash` 是截断（`0:10.9` 画成 `0:10`）。四舍五入的话 10.6s 就该叫一帧，
// 而界面那时还画着 `0:10`——那一帧白刷；反过来用毫秒判，就是每一拍都叫。
//
// # 它不认识「在不在放」
//
// 那不是它的活：暂停/停住时位置本来就不动，于是它自然报 false。而「播放器
// 卡住了、位置却还能读到一个旧值」这一档也是对 false——那时候读数确实没变。
func readoutMoved(prev, now time.Duration) bool {
	// 负数不是有效位置（`Position()` 在没装播放器时给零值）；两边都归到 0，
	// 免得「-1ns 到 0」被当成跨了一秒。
	if prev < 0 {
		prev = 0
	}
	if now < 0 {
		now = 0
	}
	return prev/time.Second != now/time.Second
}
