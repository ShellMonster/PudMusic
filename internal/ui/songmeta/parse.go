package songmeta

// 这一层是「**从标题里认出歌名**」的那一份逻辑，**显示**和**匹配**共用它。
//
// # 规则 + 词典，不是分词
//
// 「哪一段是歌名、哪一段是歌手」是**结构**问题——结构由**分隔符**承载
//（《》/【】/引号/` - `/`:`/`|`），而不是由词边界承载。
//
// ⚠️ **不用分词（jieba 那种）**：业界没有一个音乐元数据清洗用分词；唯一用到
// jieba 的项目是把它当**全文检索索引的分词器**。技术原因：jieba 是通用领域
// 分词器，「稻香」「不能说的秘密」这类歌名它都切不对。
//
// # 判据的顺序（**结构化**，不是浮点分）
//
//	① 《》「」『』引号   → 里面那一段**就是歌名**（中文歌名最常见的写法）
//	② 【】[]             → 里面那一段**可能是**歌名（「【晴天】」），也可能是
//	                        歌手（「【周杰伦】晴天」）——靠**它前后**有没有别
//	                        的段来定
//	③ 破折号 ` - ` `-`     → 分成两段，**左边是署名、右边是歌名**（通行约定）
//	④ 冒号 `:` `：`        → 分成几段，剔掉「说明」那一族，**剩下最后一段是歌名**
//	⑤ 竖线 `|`            → 同破折号（左边署名、右边歌名）
//	⑥ 空白 / 引号外       → 剔掉宣传词、说明、版本说明那些字段，**最后一段是歌名**
//
// # ⚠️ **左右哪边是歌名**
//
// 两边都没线索时是**本质歧义**（"于文文 - 体面" 和 "体面 - 于文文" 长得一样）
// ⇒ 按通行约定取 **`艺人 - 歌名`**（B 站文件名和下载工具都是这个约定）。
//
// 但**认得出歌手的时候不是歧义**：那一段是署名 ⇒ 另一段才是歌名（词典在
// `artists.go`）。

// dashSeps 是「标题里分隔两段」的那些破折号。
//
// ⚠️ **紧凑的连字符也算**（"周杰伦-晴天"）：那是 B 站上最常见的写法之一。
var dashSeps = []string{" - ", " – ", " — ", "－", "-", "–", "—"}

// colonSeps 是「标题里分隔两段」的那些冒号。
var colonSeps = []string{"：", ":"}

// pipeSeps 是「标题里分隔两段」的那些竖线。
//
// ⚠️ **它跟破折号是同一档**（左边署名、右边歌名）：B 站上「起风了 | 吴青峰 |
// 官方MV」这种写法很多，而竖线右边的「官方MV」是宣传词 ⇒ 剔掉之后歌名是
// 「起风了」。
var pipeSeps = []string{" | ", "|", "｜"}

// quotePairs 是「引号」那一对：里面装的是**歌名**。
//
// ⚠️ **它排在《》之后**（书名号那一档更明确）。
var quotePairs = []struct{ open, close string }{
	{"“", "”"},   // “Let It Go”
	{"‘", "’"},   // ‘Let It Go’
	{"\"", "\""}, // "Let It Go"
	{"《", "》"},   // 《晴天》
	{"「", "」"},   // 「晴天」
	{"『", "』"},   // 『晴天』
}

// spanPairs 是标题里那些成对的括号（**按种类分**，理由见 `spans.go`）。
var spanPairs = []struct{ open, close string }{
	{"（", "）"}, {"(", ")"},
	{"【", "】"}, {"[", "]"},
	{"《", "》"}, {"「", "」"}, {"『", "』"},
}

// hasHan 报这一段里有没有汉字。
func hasHan(s string) bool {
	for _, r := range s {
		if isHanRune(r) {
			return true
		}
	}
	return false
}

// anyHan 报这几段里有没有汉字。
func anyHan(segs []string) bool {
	for _, s := range segs {
		if hasHan(s) {
			return true
		}
	}
	return false
}

// isHanRune 报这个字是不是汉字。
func isHanRune(r rune) bool {
	return r >= 0x4E00 && r <= 0x9FFF
}
