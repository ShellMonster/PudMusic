// 歌手名的那本**小词典**。
//
// # 为什么要有它
//
// 「艺人 - 歌名」和「歌名 - 艺人」这两种写法**长得一模一样**（"于文文 - 体
// 面" 与 "体面 - 于文文"），而 B 站的文件名和下载工具都按**艺人 - 歌名**那
// 一档写——所以两边都没线索的时候按**后一段是歌名**处理。
//
// ⚠️ **但认得出歌手的时候就不是歧义了**：那一段是署名 ⇒ 另一段才是歌名。
//
//	孤勇者 - 陈奕迅 - 官方完整版   ⇒ 陈奕迅是歌手 ⇒ 歌名是「孤勇者」
//	孤勇者 - 陈奕迅                ⇒ 认不出 ⇒ 按约定取后一段 ⇒「陈奕迅」（错）
//
// ⇒ 所以「哪一边是歌名」这一档要有一本**词典**。
//
// ⚠️ **这不是分词**（jieba 那种分词器切不对「稻香」「不能说的秘密」这种歌
// 名，而且没有一个音乐元数据清洗用分词）——它只是「**哪一段是个歌手名**」
// 的一张名单。「哪一段是歌名、哪一段是歌手」是**结构**问题，由分隔符承载。
//
// # ⚠️ **词典治不了根**（票 #706 的 bug）
//
// 这本名单**收不全**——B 站上每天都有新的歌手。而**漏掉一个的后果**是：
//
//	起风了 - 吴青峰   ⇒ 词典里没有「吴青峰」⇒ 按约定取后一段 ⇒「吴青峰」
//
// ⇒ 界面上**把歌手的名字当歌名显示**——而用户看到的是「这一首叫『吴青峰』」。
// 那是**界面说谎**。
//
// ⇒ 所以「哪一段是署名」这一档是**两层**：
//
//	① **词典**（这一份）——认得出就是认得出（准确，但不全）；
//	② **形状判据**（`nameshape.go` 那一份）——认不出，但**长得像**人名 / 团名。
//
// ⚠️ **两层是「词典认不出才轮到②」**：词典认得出的那一档不准用形状去否决
// （"周杰伦 - 晴天"那一档里词典已经认得出「周杰伦」是签名，那一档就不走形状）。
//
// # ⚠️ **形状判据只用来「降级」，不用来「清空」**（票 #706 第二轮的回归修复）
//
// 上一版形状判据在「两边都像艺人名」的时候**直接让整条标题认不出**——而那一版
// 的代价被算成了「显示得更脏」。🔴 **实际代价大得多**：认不出 ⇒ 别名表是空的 ⇒
// **评论一条都筛不出来**。
//
// ⇒ 所以词典认不出、而两边都像艺人名的那一档（"白月光 - 张碧晨"）**降级**处理：
// 显示层按通行约定取一个，匹配层两个都收（见 `ident.go` 的 `dashSongName`）。
//
// # 它只是一张**启发式名单**，不是权威
//
// 名单里没有的歌手 ⇒ 那一段认不出来 ⇒ 退回「艺人 - 歌名」那个约定。所以名
// 单不需要全，够用就行（漏一个歌手的后果是那一首歌名认成歌手名；多一个的
// 后果是某个歌名被当成歌手名）。
//
// ⚠️ **别把它当歌名表**：歌名那一族是**结构**问题（`《》`/`【】`/` - `/`:`），
// 由 `parse.go` 的结构判据承载，不靠这份名单。
