// artistSet 是那份名单的**查找用**的一份（建一次，省得每次线性扫）。
//
// ⚠️ **键是「小写 + 去空白」**：名单里存的是干净的写法，而标题里那一段可能
// 带着标点或空格（"周杰伦 "、"周杰伦 "）。
var artistSet = func() map[string]bool {
	m := make(map[string]bool, len(artistNames))
	for _, n := range artistNames {
		m[artistKey(n)] = true
	}
	return m
}()

// artistKey 是「一个歌手名」的查找键：小写 + 去空白。
func artistKey(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if r == ' ' || r == '\t' || r == '\n' {
			continue
		}
		b.WriteRune(r)
	}
	return strings.ToLower(b.String())
}

// IsArtistName 报这一段是不是**词典里的艺人名**。
//
// ⚠️ **比对之前要去掉两头的标点**（"周杰伦、"）：名单里存的是干净的写法。
//
// ⚠️ **它是「哪一边是歌名」那一档唯一的凭据**（理由见文件头）。
func IsArtistName(s string) bool {
	t := strings.TrimSpace(s)
	if t == "" {
		return false
	}
	// ⚠️ **两头的标点先去掉**（"周杰伦、"、"【周杰伦】"）。
	t = strings.Trim(t, " ,，、|·・:：.。!！?？\"'“”‘’()（）[]【】《》「」『』")
	if t == "" {
		return false
	}
	return artistSet[artistKey(t)]
}
