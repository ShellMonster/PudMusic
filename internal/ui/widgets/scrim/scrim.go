// Package scrim 是「一层盖在内容上面的半透明黑」的令牌表。
//
// # 为什么单独一个包
//
// 审计（票 #212 的 F-13）数过：应用里有 **6 个浮层各写各的 alpha**
// ——同一个「压暗」这件事，六个地方各写一个数（0.55 / 0.55 / 0.5 / 0.4 / 0.35 / 0.35），
// 而其中两个**本该是同一个东西**：满屏播放器的背景压暗和裁剪框里的压暗
// 都是 0.55，可它们分写在两个文件里，改一个忘了另一个，差值就出现了。
//
// 这个包把那几档收到一处，调用处只说「要哪一档」——
// 跟 `widgets/shadow`（影子）、`widgets/space`（间距）同一个路数。
//
// # 几档分别是什么
//
//	Media   0.55 —— 媒体（背景、封面、图）被压暗。
//	Cover   0.50 —— 播放条那张封面上悬停时压暗的那一层。
//	Modal   0.40 —— 模态弹窗背后那一层背板。
//	Overlay 0.35 —— 图上盖着的一层薄黑（小浮层的底、列表行封面的压暗）。
//	Badge   0.70 —— 角标那一块底（视频封面右下角那个时长角标）。
//
// 还有一组是 **UP 空间头图区**的（那一块是**一张用户上传的任意图片**，
// 所以分两档）：整块 30% / 50%，有字的那一带再压 40% / 15%。
//
// ⚠️ **Media 那一档是两个地方共用同一个数**（满屏背景 / 裁剪框外），
// 别把它拆成两档——那正是这个包要收掉的那件事。
//
// ⚠️ **Cover 和 Overlay 压的不是同一个东西**：Cover 压的是**播放条那张封面**
// （56 见方，压暗是为了让上面的主色箭头读得出来）；Overlay 压的是
// **小浮层**（行尾那枚「⋯」的底、列表行封面上那层压暗）。
// 数值接近不等于语义相同——**别为了让它们相等而合并**。
//
// # 白色那一档
//
// `OnScrim` 是**压在深色上的白字**（0.92）。它不是遮罩，是前景色，
// 但它跟遮罩是一对（没有罩就没有这层字），所以放在这儿。
// ⚠️ **满屏播放器里那两级白（0.92 / 0.62）不在这儿**：那两个是
// 「毛玻璃背景上的前景色」，由 `fullForeground` 现算（见
// `internal/ui/fullplayer.go`），跟「压在一块纯黑上」不是一回事。
package scrim

const (
	// Media 是媒体（背景、封面、图）被压暗时那一层的 alpha。
	//
	// 满屏播放器（`fullplayer.go` 的 fullScrim）和裁剪框外那一圈
	// （`covermodal.go` 的 drawCropStage）**共用这一档**。
	Media = 0.55

	// Cover 是播放条那张封面上悬停时压暗的那一层的 alpha。
	Cover = 0.50

	// Modal 是模态弹窗背后背板那一层的 alpha。
	Modal = 0.40

	// Overlay 是图上盖着的一层薄黑的 alpha。
	//
	// 三处共用这一档：队列抽屉封面上的播放三角底（`queue_drawer.go`）、
	// 行尾那枚「⋯」的浮层底（`widgets/list/operation.go`）、
	// 列表行封面上那层压暗（`widgets/hover/hover.go` 的 dimAlpha，
	// 逐字抄上游的 `bg-black/35`）。
	Overlay = 0.35

	// OnScrim 是压在深色上的白字。
	OnScrim = 0.92

	// Badge 是**角标**那一块底（视频封面右下角那个时长角标）的 alpha。
	//
	// 上游 `src/pages/user-profile/dynamic-list/item.tsx:198` 的
	// `bg-black/70`——**70% 的黑**：角标压在封面那张照片上，要压得够黑
	// 才读得出上面那一句白字（时长）。
	//
	// ⚠️ **它不是 `Overlay`（0.35）那一档**：那一档压的是「图上盖着的一层
	// 薄黑」（小浮层的底），角标要的是**一块实打实的底板**——压 35% 的话
	// 角标在浅色封面上读不出来。
	Badge = 0.70

	// ── UP 空间头图区那两档 ──
	//
	// 头图区是**一张用户上传的任意图片**，所以它那儿的黑蒙版分两档：
	// **整块**一层（HeaderLight / HeaderDark），**有字的那一带**再一层
	// （HeaderTextLight / HeaderTextDark）。
	//
	// ⚠️ **这两档现在没有地方用**：票 #357 之后头图区的字压在**页面底色**上
	// （不再压在照片上），于是那两档黑蒙版就没人画了。留在表里是因为这张表
	// 钉着它们（`TestTheScrimValuesAreLocked`）——真要删，是另一件事。

	// HeaderLight / HeaderDark 是头图区**整块**那一层黑蒙版的 alpha。
	//
	// 上游 `src/pages/user-profile/space-info.tsx:83-86`：
	// `overlayOpacity = isDarkTheme ? 0.5 : 0.3`——**浅色 30% / 深色 50%**。
	//
	// ⚠️ **有没有头图都在这一层下面**：上游那一层是 `bg-cover` 自己的底，
	// 没有图时它是白底 × 30% 黑 = #b2b2b2（上游实图实测值）。
	HeaderLight = 0.30
	HeaderDark  = 0.50

	// HeaderTextLight / HeaderTextDark 是头图区里**有字的那一带**再压的一档。
	//
	// 为什么需要它：整块那一档是**平**的，而头图是**用户上传的任意图片**——
	// 最坏情况是一张**纯白**的头图。浅色下 30% 的黑只把纯白压到 #b2b2b2，
	// 白字压在上面只有 **2.1:1**（读不出来）；深色下 50% 只压到 #7f7f7f，
	// **4.0:1**（大字够、小字不够）。
	//
	// ⚠️ **这两档是「压到白字 ≥4.5:1」算出来的**，不是拍脑袋定的：
	// 白字要 4.5:1，它压着的底就得 ≤ #767676（相对亮度 ≤ 0.1833），
	// 于是 255×(1-整块那一档)×(1-这一档) ≤ 118.6：
	//
	//	浅色：0.7×(1-x) ≤ 0.465 → x ≥ 0.335 → 取 0.40（留一点余量）
	//	深色：0.5×(1-x) ≤ 0.465 → x ≥ 0.069 → 取 0.15（同上）
	//
	// 92% 的白（`OnScrim` 那一档）压在同样的底上还有 4.80:1 / 4.73:1，
	// 也够（算法见 `internal/ui/upspace.go` 的 `upHeaderTextDim`）。
	HeaderTextLight = 0.40
	HeaderTextDark  = 0.15
)
