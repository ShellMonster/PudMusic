// Package leading 是行高档位的表。
//
// # 为什么行高要有体系
//
// 审计（票 #212 的 F-23）数过：同一个应用里行高有**七套**——
// 列表歌名 1.5、列表 UP 名 1、设置页说明 1.5、提示 1.7、
// 歌词 1.375、关注页签名 1.4、歌词搜索结果 1.6，另有 10 处直接写字面量。
//
// 报告给的口径是「**先只把「正文/说明」那一类归到一处**，其余几处保留
// 但写进 DESIGN.md（1.375 是歌词专用的、20 固定是译文专用的——这两个是
// 刻意的）」。
//
// 这张表照那个口径做：**每一档都有名字**（名字说的是「哪一处的行高」），
// 值只写在这里。刻意保留的档（歌词 1.375、译文固定 20 像素）也在表里，
// 只是名字不同——「有名字」和「跟别处一样」是两件事。
//
// # 倍数，不是像素
//
// 这一表里的值都是**倍数**（`LineHeight(1.5)` 那种）。唯一一个不是倍数的是
// 歌词译文的**固定 20 像素**（上游 `line-height: 1.25rem`）——它走的是框架的
// `FixedLineHeight`，不是 `LineHeight`，所以**不在这个包里**（见
// `internal/ui/lyrics.go` 的 `lyricsTranslationLineHeight`）。
//
// ⚠️ **别把倍数当像素用**：1.5 倍的 12 号字是 18 像素高，
// 20 倍的 12 号字是 240 像素高——那一行会高到把整个面板撑破。
package leading

const (
	// Owner 是 UP 名 / 副题那一行的行高倍数。**1**——上游那一行是
	// `leading-none`（`music-list-item/index.tsx` 的副题）。
	//
	// ⚠️ **它是 1，不是「没写」**：不写行高的话这一行有多高由字体决定，
	// 而那会让「一行小字和旁边那一行齐不齐」变成看运气。
	Owner = 1.0

	// Compact 是紧凑一档（网格紧凑卡）那几行的行高倍数。**1.2**。
	Compact = 1.2

	// Lyrics 是歌词那一行的行高倍数。**1.375**——抄上游的 `leading-snug`
	//（`lyrics/index.tsx`）。
	//
	// ⚠️ **它是歌词专用的**：1.375 是 22/16，行与行之间比 1.5 紧，
	// 而歌词是要连着唱下去的，紧一点才接得上。
	Lyrics = 1.375

	// Signature 是关注页那一行签名的行高倍数。**1.4**。
	Signature = 1.4

	// Title 是歌名 / 标题那一行的行高倍数。**1.5**——Tailwind 的默认行高。
	Title = 1.5

	// Copy 是小字说明那一行的行高倍数。**1.5**——和 `Title` 同一个数。
	//
	// ⚠️ **它是另一个名字，不是另一个数**：歌名和小字说明都用 1.5，
	// 但它们是两处不同的东西（一个是标题、一个是注释），
	// 各叫各的，改起来才知道改的是哪一处。
	//
	// ⚠️ **不写行高的话，这一行有多高是字体决定的**：同一个字号在不同字体下
	// 差几个像素，而那几像素会让「一行小字和旁边那一行齐不齐」变成看运气。
	Copy = 1.5

	// Result 是歌词搜索结果那一行的行高倍数。**1.6**。
	Result = 1.6

	// Hint 是 11px 提示那几行的行高倍数。**1.7**。
	//
	// ⚠️ **为什么比别处大一点**：11 × 1.5 = 16.5，而旁边 12px 的那些是 18——
	// 一行字的高度差两像素，弹窗里那几行看着就错开了。1.7 给到 18.7，
	// 和 12px 的那些齐。
	Hint = 1.7
)
