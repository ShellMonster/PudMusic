// 「按下时缩一点」那一档反馈。
//
// # 0.96 这个数从哪来
//
// 手册 ⓪：「按钮 active 如果要缩小，一般 0.96 甚至更大就够了；如果是放大，
// 一般 1.04 就够了。」
//
// 所以这里有两个数：缩的那一档是 **0.96**，放的那一档是 **1.04**。用哪一档由
// 调用点自己挑（`PressShrink` / `PressGrow`）——**按钮的形状不一样，缩和放的
// 观感也不一样**，所以两个都留着，而不是写死一个。
//
// # ⚠️ 缩放加在**内容**上，不加在按钮盒子上
//
// 框架的命中测试按**画出来**的框算（`mygo/ui/transform.go` 的 `contains`
// 反解 `s.world`），所以给按钮盒子自己加 Scale 会连着把**命中区**缩小 4%：
// 指针正好压在边缘那一像素时 `Pressed()` 会翻成 false，缩放于是**自己抖起来**
// （实测：40px 的盒子缩到 0.96 后，x=139.2 起就按不到了）。
//
// 缩放加在**内容**（图标）上就没有这个问题：按钮的盒子还是那么大，命中区不动，
// 缩的只是画出来的东西。
//
// # ⚠️ 只给**图标**用
//
// 文字被 Scale 缩放会**重采样**：字形先按字号栅格化，再被变换缩一次，笔画
// 的边缘于是糊掉。实测 14px 的「赞」字缩到 0.96，跟直接用 13.44 的字号画出来
// 相比——**实心笔画少 13 像素（17 vs 30）、中间调的边缘多 23 像素（113 vs 90）**
// （2x 下是 151 vs 178 / 296 vs 216）：变换缩放出来的那一份明显更软。
//
// 所以 `flat` 这一档只给图标键用；纯文字的按钮（`flat.Button`）**不缩**——
// 它们那一档反馈是 `feel` 铺的那层半透明底（hover 0.08 / 按下 0.16）。
//
// # ⚠️ 动画通道的键必须是常量
//
// 框架把动画的值存在元素状态的一个 map 里，键是 `any`——传一个每次都要装箱的
// 字符串，每一帧就多一次分配（实测 `AnimateWith` 传常量字符串是 0 分配，传变量
// 就不是了）。所以这里是 `const` 而不是 `var`。
//
// ⚠️ **一个键就够**：动画通道存在**元素自己的状态**里，而每个图标是各自的
// 元素——同一个键在不同的元素上是不同的通道。
//
// # ⚠️ 元素的身份要稳（兄弟序号变了，通道会被别人继承）
//
// 框架给元素的默认身份是「父 ID + 兄弟序号」。前面插进一枚键，后面所有键的
// 身份就都变了，而**动画通道是存在身份里的**——于是新来的那枚键会**继承**上一
// 枚留下的通道（画面上是「另一枚键莫名其妙缩着」）。
//
// 播放条左边那一段就是这种地方：「分集」键是逐帧问出来的（单 P 的稿子不摆），
// 于是「收藏 / 赞」的兄弟序号会变。**那一段的三枚键都用 `Context.Key` 钉了
// 身份**（见 `internal/ui/playbar.go`）。别的地方兄弟是不变的，就不用管。
package flat

import (
	"time"

	"github.com/ShellMonster/Biu_Go/internal/ui/widgets/motion"
	"github.com/egoist/mygo/ui"
)

// 按下时缩 / 放的那个倍数。
//
// ⚠️ **0.96 是「缩」那一档**（手册 ⓪：「按钮 active 如果要缩小，一般 0.96
// 甚至更大就够了」），**1.04 是「放」那一档**（「如果是放大，一般 1.04 就够了」）。
const (
	// PressShrink 是按下时**缩到**的倍数。
	PressShrink = 0.96
	// PressGrow 是按下时**放到**的倍数。
	PressGrow = 1.04
)

// pressTime 是缩放走完要多久。
//
// ⚠️ **不是零**：零的话按下是「啪」地一下缩到底，松手也是「啪」地一下弹回来，
// 而按钮的按下反馈是要能看出「按下去」这件事的。
//
// 120ms 是按压这种「一按就松」的反馈该有的长度：短到不拖沓，长到看得见。
const pressTime = 120 * time.Millisecond

// pressKey 是「按下缩放」这条动画通道的键。
//
// ⚠️ **必须是常量**：理由见文件头那一段——而且这不是洁癖：**一个变量的字符串**
// 装进框架那个 `any` 形参要**每帧一次装箱分配**（实测：歌词区那三枚旋钮钉身份
// 时，满屏播放器那一档每帧多 3 次——正是那三枚），而**常量**由编译器给一个静态
// 的值，一次也不分配 ✓。
const pressKey = "flat:press"

// PressScaleValue 给出内容 e 这一帧该缩到多少（1 = 原样）。
//
// pressed 是「按着没有」——**问按钮的 `Pressed()`**，不是问内容的（内容不是
// 可点的，问它自己永远问不到）。
//
// grow 为真时是「放到 1.04」，为假时是「缩到 0.96」。
//
// ⚠️ **每一帧都要问**（哪怕这一帧没按着）：框架的动画通道是**第一次**问某个键
// 时直接给目标值（`mygo/ui/motion.go` 的 `if made { return target }`），
// 而不问的那一帧就永远是「第一次」——于是第一次按下立刻就是终值，没有过渡。
func PressScaleValue(e ui.Element, pressed, grow bool) float32 {
	target := float32(1)
	if pressed {
		if grow {
			target = PressGrow
		} else {
			target = PressShrink
		}
	}
	// ⚠️ **这一档换不了 `AnimatePose`**（票 #276 查过）：它的返回值是**被读**的
	// ——调用方拿它去乘（`like.go` 的图标层把这一档和「弹出来」那一档相乘），
	// 而 pose 的当前值**没有公开的读法**（`mygo/ui/pose.go`）。判据只有一条：
	// **换完之后那个动画值还会不会被 view 读**——会读就还是每帧重建，就白换。
	return e.AnimateWith(pressKey, target, pressTime, motion.Unified)
}

// PressScale 给内容 e 装上「按下时缩到 0.96（放则 1.04）」这一层，返回同一个 e。
//
// ⚠️ **e 要是按钮的**内容**（图标），不是按钮盒子**——理由见文件头。
//
// ⚠️ **跟别的缩放要相乘**：框架的 `Scale` 是「在已有变换**之后**再缩」
// （`mygo/ui/transform.go`：`e.transform = e.transform.Then(Scaling(x, y))`），
// 所以两次 `Scale` 本身就是乘在一起的——但要跟别的一档相乘时（比如赞键那种
// 「按下 + 弹跳」），用 `PressScaleValue` 拿到倍数，**自己乘完再 `Scale` 一次**：
// 那样只有一份变换，读者一眼看得出乘的是哪两个。
func PressScale(e ui.Element, pressed, grow bool) ui.Element {
	v := PressScaleValue(e, pressed, grow)
	return e.Scale(v, v)
}
