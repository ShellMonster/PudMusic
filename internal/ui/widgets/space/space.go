// Package space 是全应用的间距表：`.Gap()` / `.Padding()` / `.Margin*()`
// 的实参都从这里取，别再写数字。
//
// # 为什么单开一个包
//
// 间距是全应用**最散**的一类数。审计（票 #212 的 F-10）数过：字面量间距
// **335 个调用点 / 72 个文件**，367 个纯数字实参里 96% 是裸数字——
// 改之前（本票动手时的 `2f8fcd6`）：**同一个 8 在 80 个实参里各写各的，
// 同一个 6 在 38 个地方各写各的**。
//
// 画面上**看不出**差别（差一两个像素的那一处，谁都说不清哪儿不齐），
// 所以这类漂移从来不会被发现，只能靠「值只写一处」兜住。
//
// 做法跟 `widgets/ink`（颜色）、`widgets/shadow`（阴影）、`widgets/scale`
// （字号）一样：**值只写在这里，调用处只说「要哪一档」**。
//
// # 刻度
//
// 基础单位是 **4 像素**（DESIGN.md `spacing.unit`；Tailwind 1 单位 = 4px）。
// 这一档的名字是**这一档的像素值**，注释里写它是几格：
//
//	None = 0        Px2  = 2  （½ 格）    Px4  = 4  （1 格）
//	Px6  = 6  （1½ 格）   Px8  = 8  （2 格）    Px10 = 10 （2½ 格）
//	Px12 = 12 （3 格）    Px16 = 16 （4 格）    Px20 = 20 （5 格）
//	Px24 = 24 （6 格）    Px28 = 28 （7 格）    Px32 = 32 （8 格）
//	Px48 = 48 （12 格）
//
// ⚠️ **名字里直写像素值是有意的**：这一版是**机械替换**（四百多处），
// 「6 → Px6」在 diff 里一眼就能核对；而「6 → Md」得回表里查一趟才知道是几。
// 档与档的关系写在上面那段注释里，查表只需要看它。
//
// # 不在刻度上的那几档
//
//	Px1 = 1    Px3 = 3    Px5 = 5    Px7 = 7    Px9 = 9
//
// 这些是 4 的刻度之外的**四分之一步**（¼、¾、1¼、1¾、2¼ 格）。
// **它们多半不是设计刻度，是尺寸的推论**：把一个图标摆在方形热区正中，
// 左右的内边距是 (热区 − 图标) / 2 —— 32 减 18 除 2 是 7，32 减 14 除 2 是 9。
//
// ⚠️ **归一是另一票的事**：把 7 收成 6 或 8 是**布局改动**，画面会变。
// 这一票只搬不改——一个像素都不许动。
//
// 还有一个 **Px90 = 90**（22½ 格）：提示那一块要让开播放条（高 88），
// 上游的 `toastOffset` 就是 90（DESIGN.md §三「Toast | 宽 356、距底 90」）。
// 它也不是 4 的刻度上的数，但**有出处**，所以进表。
//
// # DESIGN.md 的令牌
//
// 下面五个别名是 DESIGN.md `spacing` 一节里的那几个数，**值必须和那里一样**
// （`space_test.go` 里那条测试盯着，它直接读仓库根的 DESIGN.md）：
//
//	Unit             = 4   spacing.unit
//	PageHorizontal   = 16  spacing.page_horizontal
//	PageVertical     = 0   spacing.page_vertical
//	ListGap          = 16  spacing.list_gap
//	SettingsGroupGap = 24  spacing.settings_group_gap
//
// ⚠️ **别名是「角色名」，刻度名是「值名」**：一个值在表里有两个名字。
// **角色成立的地方留一个角色常量，它的值从别名来**——比如页面那一层的横向
// 内边距是 `pagePadX = space.PageHorizontal`（`internal/ui/pagerhythm.go`），
// 设置分组间距是 `settingsGroupGap = space.SettingsGroupGap`。
// 别处直接用刻度名（网格格间距用 `space.Px16`）。
// 别名不产生第二份值——它们就是刻度名的另一个写法。
//
// # 框架那个 t.Space(n) 呢
//
// 框架给了 `t.Space(n)`（n × 主题的 `Spacing`，默认 4），应用里也还留着
// 二十几处调用。**那是「按主题算」的一个入口，跟本表是同一个刻度**
// （`t.Space(2)` = 8 = `Px8`），但它不是字面量，所以这一版不动它：
// 把「主题说了算」换成「常量说了算」是语义变化，不是换写法。
package space

const (
	// Unit 是间距的基本单位：4 像素（DESIGN.md `spacing.unit`）。
	Unit = Px4

	// None 是 0。
	None = 0

	// Px2 是 2 像素（半个格子）。
	Px2 = 2
	// Px4 是 4 像素（一格 = Unit）。
	Px4 = 4
	// Px6 是 6 像素（一格半）。
	Px6 = 6
	// Px8 是 8 像素（两格）。
	Px8 = 8
	// Px10 是 10 像素（两格半）。
	Px10 = 10
	// Px12 是 12 像素（三格）。
	Px12 = 12
	// Px16 是 16 像素（四格）——页面左右内边距、列表列间距、网格格间距都是这一档。
	Px16 = 16
	// Px20 是 20 像素（五格）。
	Px20 = 20
	// Px24 是 24 像素（六格）——设置分组间距是这一档。
	Px24 = 24
	// Px28 是 28 像素（七格）。
	Px28 = 28
	// Px32 是 32 像素（八格）。
	Px32 = 32
	// Px48 是 48 像素（十二格）——满屏播放器底部那一排的左右内边距是这一档
	//（上游的 `px-12`）。
	Px48 = 48

	// Px1 是 1 像素（¼ 格）。**不在刻度上**，见包注释。
	Px1 = 1
	// Px3 是 3 像素（¾ 格）。**不在刻度上**，见包注释。
	Px3 = 3
	// Px5 是 5 像素（1¼ 格）。**不在刻度上**，见包注释。
	Px5 = 5
	// Px7 是 7 像素（1¾ 格）。**不在刻度上**，见包注释。
	Px7 = 7
	// Px9 是 9 像素（2¼ 格）。**不在刻度上**，见包注释。
	Px9 = 9
	// Px90 是 90 像素（22½ 格）。**不在刻度上**，见包注释：提示要让开播放条
	// （高 88），上游的 `toastOffset` 就是 90（DESIGN.md §三「Toast | 距底 90」）。
	Px90 = 90

	// PageHorizontal 是内容区左右内边距：16 像素
	//（DESIGN.md `spacing.page_horizontal`）。
	PageHorizontal = Px16
	// PageVertical 是内容区上下内边距：0 像素
	//（DESIGN.md `spacing.page_vertical`；上游没有 py）。
	PageVertical = None
	// ListGap 是列表那一行里各列之间的间距：16 像素
	//（DESIGN.md `spacing.list_gap`）。
	ListGap = Px16
	// SettingsGroupGap 是设置页分组之间的间距：24 像素
	//（DESIGN.md `spacing.settings_group_gap`）。
	SettingsGroupGap = Px24
)
