// 播放条那三枚键的读数折法（票 #701）。
//
// # 这一组断的是「折法本身」
//
// 它是一份**纯函数**的契约：每一档的边界值折成什么字。而那一族最要紧的
// 性质是**宽度恒定**（理由见 `count.go` 的文件头）——所以折法一旦改了宽度，
// 播放条左列就可能撞上进度条滑块（票 #216 那个坑）。
package list

import (
	"strings"
	"testing"
)

// TestCountTextFoldsAtEveryBoundary 钉住**每一档的边界值**。
//
// ⚠️ **边界值一个都不能少**：折法是「区间 → 字」的映射，而区间之间的缝就是
// 边界——只断中间那个数的话，改成 `<` 而不是 `<=`（或者差一）它照样绿。
//
// 🔴 **`100000` 那一档是封顶**：100000 / 999999 / 10000000 / 一亿 全都是
// 「1亿+」。这一条是这一族**宽度恒等**的保证（理由见 `count.go` 的文件头）。
//
// ⚠️ **注意 `99999` → 「99k+」，而 `100000` → 「1亿+」**：这两个是**不同的档**
// （封顶那一档从 100000 起），所以边界上「99k+」和「1亿+」挨着。
func TestCountTextFoldsAtEveryBoundary(t *testing.T) {
	cases := []struct {
		n    int64
		want string
	}{
		// ⚠️ **0 和负数是「没有这个数」**：空串，不是「0」。
		{0, ""},
		{-1, ""},
		{-1286, ""},

		// 0 – 999：精确数字，**不带 `+`**。
		{1, "1"},
		{9, "9"},
		{99, "99"},
		{998, "998"},
		{999, "999"},

		// 1000 – 9999：「Nk+」（至少 N 千）。
		//
		// ⚠️ **1000 折成「1k+」而不是「999+」**：前者 16.28 宽，后者 25.87——
		// 而这一族的宽度余量只有几个像素（`count.go` 的文件头）。
		{1000, "1k+"},
		{1234, "1k+"},
		{1999, "1k+"},
		{2000, "2k+"},
		{9998, "9k+"},
		{9999, "9k+"},

		// 10000 – 99999：「Nk+」（按**千**向下取整，不是按万）。
		{10000, "10k+"},
		{10001, "10k+"},
		{19999, "19k+"},
		{20000, "20k+"},
		{89999, "89k+"},
		{99999, "99k+"},

		// ≥ 100000：**封顶**「1亿+」。
		{100000, "1亿+"},
		{999999, "1亿+"},
		{1000000, "1亿+"},
		{10000000, "1亿+"},
		{100000000, "1亿+"},
		{99999999999, "1亿+"},
	}
	for _, c := range cases {
		if got := CountText(c.n); got != c.want {
			t.Errorf("CountText(%d) = %q，want %q", c.n, got, c.want)
		}
	}
}

// TestCountTextNeverUnderstatesTheValue 钉住**不许低估**。
//
// 🔴 票面原话：「拿 `+` 表示「精确等于」就是撒谎」——而**低估**是同一种撒谎的
// 另一种形态：那一档实际是「至少 1000」，写成「99+」（至少 99）就是骗用户说
// 那个数比实际小。
//
// ⇒ 判据是「折出来的那一栏，其**下界**不许大于真实值」。
//
// ⚠️ **怎么判下界**：每一档的输出头都是一个数（`1k+` 的 1、`100k+` 的 100），
// 而它的单位由倒数第二个字母决定（k = 千）。所以：
//
//	输出的下界 = 头 × 单位
//
// ⚠️ **「封顶」那一档是唯一的例外**（「1亿+」）：它对 100000 那个数**是夸大的**
// ——「至少 1 亿」而真值是 10 万。那是**故意的**（理由见 `count.go` 的文件头
// 《为什么 ≥100000 那一档是「1亿+」》）：票面那一档原本是「10w+」（至少 10 万），
// 而它实测 25.25 装不进上限 24.5。
//
// ⇒ 所以这一条**把那一档单独挑出来**：它不许被**低估**（那一档本来就是夸大的），
// 但它**必须存在**（不能是空串——空串是「没有这个数」）。
func TestCountTextNeverUnderstatesTheValue(t *testing.T) {
	// 单位：k = 千、亿 = 一亿。
	//
	// ⚠️ **「亿」这个单位必须认出来**：不认的话「1亿+」的下界会算成 1，
	// 而那一档就**永远验不到**——那是一个覆盖盲点（这一条的第一版就踩过）。
	unit := func(s string) int64 {
		switch {
		case strings.Contains(s, "亿"):
			return 100_000_000
		case len(s) >= 2 && s[len(s)-2] == 'k':
			return 1_000
		}
		return 1
	}
	// 输出的下界（那个头 × 单位）。
	lower := func(s string) int64 {
		if len(s) == 0 {
			return 0
		}
		var head int64
		for _, r := range s {
			if r >= '0' && r <= '9' {
				head = head*10 + int64(r-'0')
			} else {
				break
			}
		}
		return head * unit(s)
	}
	// ⚠️ **「1亿+」那一档单独判**：它对 100000 那个数是**夸大的**（故意的），
	// 所以「不许低估」那一条**不适用**于它——但它**必须画得出**。
	for _, n := range []int64{
		1, 9, 99, 999, 1000, 1234, 9999, 10000, 12345, 99999,
	} {
		got := CountText(n)
		if got == "" {
			t.Fatalf("CountText(%d) = 空串——那一档该有字", n)
		}
		lo := lower(got)
		if lo > n {
			t.Errorf("CountText(%d) = %q，而那一档的下界是 %d——**低估了**"+
				"（票面禁止拿一种撒谎表示另一种）", n, got, lo)
		}
	}
	// 封顶那一档：不是空串，而且**装得下上限**（那个「+」不许被切）。
	for _, n := range []int64{100000, 999999, 10000000, 100000000, 99999999999} {
		got := CountText(n)
		if got == "" {
			t.Errorf("CountText(%d) = 空串——封顶那一档也得有个字", n)
			continue
		}
		if !strings.HasSuffix(got, "+") {
			t.Errorf("CountText(%d) = %q——那个「+」是这一族的语义，不许丢", n, got)
		}
	}
}

// TestCountTextIsNotThePlayCountFold 钉住**它和播放量那一族的折法是两件事**。
//
// 🔴 **不许拿 `PlayCountText` 顶替**：那一族折成「1.2万」「1.2亿」，而这一族
// 折成「1k+」「99k+」「1亿+」——两者的宽度差着一截（「1.0万」24.81 /
// 「12.3万」31.13 vs 「9k+」18.01 / 「99k+」24.49）。用错了折法，900 宽下左列
// 就撞滑块。
//
// ⚠️ **判据是「两者在同一个数上不一样」**：钉的是「它们是两套折法」这件事，
// 而不是逐个钉某一档（那一条由 `TestCountTextFoldsAtEveryBoundary` 管）。
func TestCountTextIsNotThePlayCountFold(t *testing.T) {
	same := 0
	for _, n := range []int64{1000, 9999, 10000, 12345, 100000, 1234567, 100000000} {
		if CountText(n) == PlayCountText(n) {
			same++
		}
	}
	if same == 7 {
		t.Error("CountText 和 PlayCountText 在所有档上折出来一样——" +
			"这一族该用的是自己的折法（宽度恒定），不是「1.2万」")
	}
}

// TestCountTextNeverGetsWiderThanTheCap 钉住**折法的宽度上界是恒定的**。
//
// 🔴 **这是这一族最要紧的性质**（理由见 `count.go` 的文件头）：数字格要是能
// 变宽，900 宽的窗口上左边那一列就会撞上进度条滑块左沿——而那一撞是
// **点不动**（票 #216：中间那一列是 `PassThrough` 的，可它的子节点照旧登记
// 命中，于是左列撑出来的那一截被进度行的命中框盖住），**画面上看不出坏了**。
//
// ⚠️ **判据是「输出的字在那个集合里」**：这一族一共只该有这几种字，而每一种
// 的宽度都是量过的（10 号字下 `100k+` 29.11 / `99k+` 24.49 / `10k+` 22.70 /
// `9k+` 18.01 / `1k+` 16.28 / `999` 19.45 / 纯数字更窄）。出现集合外的字就是
// 折法漏了一档。
func TestCountTextNeverGetsWiderThanTheCap(t *testing.T) {
	allowed := map[string]bool{
		"":     true, // 没有这个数
		"1k+":  true,
		"2k+":  true,
		"3k+":  true,
		"4k+":  true,
		"5k+":  true,
		"6k+":  true,
		"7k+":  true,
		"8k+":  true,
		"9k+":  true,
		"10k+": true,
		"19k+": true,
		"20k+": true,
		"89k+": true,
		"99k+": true,
		"1亿+":  true,
	}
	// 纯数字那一档（1 – 999）：没有 `+`。
	for n := int64(1); n <= 999; n++ {
		got := CountText(n)
		if got == "" {
			t.Fatalf("CountText(%d) = 空串——那一档是精确数字，不该没有", n)
		}
		for _, c := range got {
			if c < '0' || c > '9' {
				t.Fatalf("CountText(%d) = %q——那一档是精确数字，不该带别的字符", n, got)
			}
		}
	}
	// 折出来的那几档，字符串必须是集合里的那一个。
	for _, n := range []int64{1000, 9999, 10000, 99999, 100000, 999999, 100000000} {
		got := CountText(n)
		if !allowed[got] {
			t.Errorf("CountText(%d) = %q，不在允许的那几个字里", n, got)
		}
	}
}
