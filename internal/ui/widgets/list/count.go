// 播放条上那三枚键（赞 / 收藏 / 评论）旁边那个**读数**的折法。
//
// # 为什么和 `PlayCountText` 是两个函数（不是同一套折法）
//
// `PlayCountText` 是**播放量**那一族的折法（「1.2万」「1.2亿」）：它在列表行和
// 网格卡片的封面底下，**地方宽**（网格卡片封面底部那一条只有 22 高——七位数那一
// 串字直接盖过封面去了），而它要的是「**约数**」。
//
// 这一族是**播放条左边第三段**那三枚键的读数：地方**一点也不宽**——900 宽的
// 窗口上左边那一列离进度条滑块只剩几像素（票 #682 / #701 量出来的），而三枚键
// 都要带着各自的数。
//
// ⇒ 所以这一族要的是**宽度恒定**的那一套折法：宁可粗一点，也不能让某一档的数
// 把左列撑到撞上滑块。
//
// 🔴 **撞上的后果是「点不动，而画面上看不出坏了」**（票 #216 那个坑）：中间那一列
// 是 `PassThrough` 的（它自己那一个框不接指针），但它的**子节点**照旧登记命中，
// 于是左列撑出轨道的那一截上的键会被进度行那一块的命中框盖住。
//
// # 为什么「+」恒表示「至少这么多」
//
// `1k+` 不是「等于 1 千」，而是「**至少 1 千**」；`1亿+` 是「**至少 1 亿**」。
// 用户看到的永远是**下界**，而精确的数在别处（收藏夹页 / 评论页页头）。
// 拿 `+` 表示「精确等于」就是撒谎——那一条会被一眼看穿。
//
// ⚠️ **不许用低估的表达**：那一档实际是「至少 1000」，就不能写成「99+」
// （那是「至少 99」，**低估**了）。宁可换一个单位，也不撒谎。
//
// ⚠️ **而「低估」是这一族最容易犯的错**：按「万」折的话，10000 ~ 99999 那一档
// 会折成「1w+」——而那个档的真实范围是 10000 ~ 99999，「1w+」说的是「至少
// 1 万」，对 99999 那个数是**低估**。
//
// ⇒ 所以「万」这一族**整个不能用**，而「10w+」（实测 25.25）又装不进数字格的
// 上限——**这一族只有「千」和「亿」两个单位**。
//
// # 四档（票 #701）
//
//	0 – 999          精确数字        「1」「99」「999」
//	1000 – 9999      「1k+」…「9k+」  至少 1 千 … 至少 9 千
//	10000 – 99999    「10k+」…「99k+」至少 10 千 … 至少 99 千
//	≥ 100000         「1亿+」        至少 1 亿（封顶）
//
// # 🔴 **最宽的那一档必须装得下上限，一档都不许靠截断兜底**
//
// ⚠️ **截断切的是末尾，而「+」永远是最后一个字符** —— 所以「+」**总是第一个被
// 切掉的东西**。实测（像素墨迹量法）：
//
//	「99k+」上限 24   → 墨迹 20.00（完整 24.49）⇒ 被截
//	「99k+」上限 21   → 墨迹 14.00 —— 比不带「+」的「99k」（18.52）**还短**
//	                    ⇒ 「+」被切掉了
//
// ⇒ 而「+」是这一族的**语义**（「至少这么多」）——它被切掉就变成了「正好 99
// 千」，那是**撒谎**。
//
// ⇒ 所以上限（`playbarCountMaxW` = 24.5）**必须 ≥ 最宽那一档的实测宽**
// （`99k+` 24.49），而折法**不许**折出装不下的字。
//
// ⚠️ **当前折法一档都不截**：最宽的「99k+」24.49 ≤ 上限 24.5 ⇒ 上限是
// **保险**，而**「100…」那个形状压根不存在**（封顶的那一档是「1亿+」23.61，
// 而「100k+」那一档早就被「1亿+」替掉了）。
//
// ⚠️ **为什么 1000–9999 那一档是「1k+」而不是「999+」**：**宽度**——「999+」
// 实测 **25.87**，装不进 24.5；而「1k+」是 **16.28**。
//
// ⇒ 而**两者语义一样诚实**：「1k+」（至少 1 千）＝「至少 1000」，而「999+」
// （至少 999）说的是「至少 999」——对 1000 那个数**低估**了。⇒ 「1k+」既更
// 窄又更准。
//
// ⚠️ **为什么 ≥100000 那一档是「1亿+」**：**宽度**——「100k+」实测 **29.11**，
// 装不进 24.5（而截断会**先切掉那个「+」**）；而「1亿+」是 **23.61**，装得下。
//
// 🔴 **「1亿+」那一档是**夸大的近似**——这不是「至少」，是「量级」**
//
// 对 100000 那个数（10 万）说「至少 1 亿」**不成立**：那一档的真实意思是
// 「**这一首的数字在十亿量级**」，而**不是**「至少 1 亿」。
//
// ⚠️ **所以那一档不许被读成精确下界**：用户看到「1亿+」时，它说的是「很多」，
// 不是「至少一亿」。
//
// ⇒ **完整的数在两处**，而**那两处给的是完整数字**（不是折过的字）：
//
//	**评论页页头**   「共 N 条」
//	**悬停提示**     「整个稿件 1234567」（票 #701 的要求——那一格没有宽度限制）
//
// ⇒ **这就是那一档唯一的代价**（而它换来的是「+」**不被切**）：一个在十亿量级
// 那一档的近似读数。票面那一档原本是「10w+」（至少 10 万，**语义准确**），
// 而它实测 25.25 装不进上限 24.5 —— 而**上限再降就会切掉那个「+」**（截断切
// 末尾，而「+」永远是最后一个字符）。⇒ 「1亿+」是「**保住「+」**」换来的
// 那一档近似。
package list

import "strconv"

// countK 是「千」那一档的单位：1000。
const countK = 1_000

// CountText 是播放条上那三枚键的读数该显示的字。
//
// ⚠️ **n <= 0 返回空串**：那是「没有这个数」（还没问回来 / 离线 / 本地文件 /
// 音乐库音频），而**空串不是 0**——调用方靠它决定画不画那个数字。画一个「0」
// 会让用户以为这一首真的零赞零收藏。
//
// # 四档（理由见文件头）
//
//	0 – 999          精确数字
//	1000 – 9999      「1k+」…「9k+」（千，向下取整）
//	10000 – 99999    「10k+」…「99k+」（千，向下取整）
//	≥ 100000         「1亿+」（封顶）
//
// ⚠️ **「1亿+」是封顶档**：再往上也是「1亿+」。
func CountText(n int64) string {
	switch {
	case n <= 0:
		return ""
	case n < countK:
		// 0 – 999：**精确数字**（不带 `+`）——999 就是 999，不是「999+」。
		return strconv.FormatInt(n, 10)
	case n < 100*countK:
		// 1000 – 99999：按**千**向下取整（不是按万——「1w+」在 99999 那一档是
		// 低估，文件头那一段）。
		//
		// ⚠️ **不许写成「999+」**（票面最初拍的那一档）：它实测 25.87 宽，装不进
		// 数字格的上限（24.5）——而截断**先切掉那个「+」**（文件头那一段）。
		return strconv.FormatInt(n/countK, 10) + "k+"
	default:
		// 🔴 **封顶**：100000 以上一律「1亿+」。
		//
		// ⚠️ **它装得下上限**：实测 23.61 ≤ 24.5 —— 所以这一档**不会被截**，
		// 那个「+」**留着**（它是这一族的语义）。
		return "1亿+"
	}
}
