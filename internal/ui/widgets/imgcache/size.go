// 「这一格该向图床要多大的图」——按显示尺寸算，不是按固定档位。
//
// # 为什么不能一刀切
//
// 界面上用到封面的地方尺寸差十倍：侧栏收藏 32 DIP、列表行 48、播放条 52、
// 首页推荐 96、歌单页 200×168、满屏 384×288。而缓存里存的一直是**长边 768**
// ——那是按最大的那一处（满屏，384 DIP @2x = 768）定的，于是其余每一处都在
// 「解一张比需要的大十几倍的图」。
//
// 一张 768×432 在内存里是 1.33MB 的 RGBA（加 mipmap 约 1.77MB）；而列表行
// 真的只需要 96×96（0.04MB）——**四十多倍**。一屏十几张、翻几十个页面之后，
// 差的就是那几十 MB。
//
// # 为什么是「显示尺寸 × 屏幕倍率」
//
// 那是**不糊的最小值**（Retina 上一个 DIP 占两个物理像素，给少了要插值放大）。
// 多要的每一像素都直接是 4 字节内存，所以这里不预留「用户可能把窗口拉大」的
// 余量——窗口变大时布局会重建、这一格拿到的新尺寸就变了，缓存按新 key 再去要
// 一张（旧的自然被 LRU 挤掉）。
//
// # 和 `maxStoredSide` 的关系
//
// `maxStoredSide` 从「所有图都缩到它」变成「**上限**」：再大的显示尺寸也不
// 超过它。它仍然是内存和磁盘两边共同的那条线。

// coverPixelSize 把**显示尺寸（DIP）**换成该向图床要的**像素尺寸**。
//
// scale 是屏幕倍率（Retina 是 2，普通屏是 1）。返回的长边已经吸到
// `snapToTier` 的某一档，并且不超过 `maxStoredSide`。
//
// ⚠️ **量不出显示尺寸时返回 0×0**：那意思是「**这一格要多大不知道**」，
// 而 0×0 让调用方**按原图走**（不裁、不缩）——见 `GetSized`。
//
// # 为什么不是「给最小的那一档」
//
// 以前的规则是「量不出来就给 64×64 那一档」，那是**从「量不出来」推出「小」**，
// 而这个推理是错的：
//
//   - 布局还没算完的那些调用点，量不出来是因为**真的还没算出来**，那一次用
//     原图是对的（只是慢一点）；
//   - **通栏**那一格量不出来，是因为**它是通栏**（要的就是整行那么宽），
//     不是「小」——按 64×64 要图等于把一张通栏横幅变成一张正方形缩略图，
//     **横幅的两端直接丢掉**（票 #630 实测：请求的是
//     `top_photo.jpg@64w_64h_1c.webp`，画面上横幅那一带一个像素都没有）。
//
// # ⚠️ **「原图是唯一安全的选择」这句话只对「通栏」那一种成立**
//
// 对**通栏**（要的是整行那么宽、而量不出宽度）原图确实是安全的：它至少是
// **全的**，横着铺开也不会丢两端。
//
// 但对**小格子**（头像、缩略图——它们要的就是 40~128 像素那么一小块），
// 原图意味着**下几百 KB**（B 站的头像原图是正方形几百 KB）——**不糊**是
// 真的（显示的就是原图那一块），但**内存和流量**是白花的几十倍。
//
// ⇒ **今天仓库里没有别的传 0 的调用点**（2026-10-27 核过：横幅那一格已经
// 改成传**真正显示的宽**了，见 `upspace.go` 的 `spaceContentWidth`），所以
// **眼下没有用户可见的损害**。
//
// ⇒ **但接进来的人要自己权衡**：要是你新加的调用点量不出尺寸，而它是一格
// **小图**——那就先把它**量出来**（`Bounds()` 上一帧的盒子、或按显示尺寸
// 算），别靠这条规则兜着。
//
// ⚠️ **这条规则落在缓存层，不是每一处各自决定**：将来有人再传 0，会被同一条
// 规则接住——**接住不等于适合**（见上面那一段）。
func coverPixelSize(w, h, scale float32) (int, int) {
	return coverPixelSizeCapped(w, h, scale, 0)
}

// coverPixelSizeCapped 是 `coverPixelSize` 加一个「**这一格最多要多大**」的上限。
//
// cap 是**长边的上限**（像素），0 = 不限。
//
// # 为什么需要它
//
// 有一格**故意**要大的那一档：满屏播放器的背景。它按**整窗**的尺寸要图
// （`GetSized(url, winW, winH)`）——而整窗 @2x 是 2400×1600。
//
// ⚠️ **但它真正需要的源图只有 600×400**：背景是画到 `winW/4 × winH/4`
// （300×200）的画布上、再放大 4 倍铺满整窗的，而 `ui.Cover` 那一步就已经把
// 源图缩到画布了。⇒ 要 2400×1600 是**多要了 16 倍像素**，而它是**每次开满屏
// 都要的**（网络字节 ×10）。
//
// ⇒ **上限由那一格自己传**（它知道自己要多少），而不是加一个全局上限——
// 全局上限会把横幅那一格（980 DIP @2x = 1960 像素）也挡住。
//
// ⚠️ **上限改了之后比例仍然要正**：长边被上限夹住时，短边要**跟着按比例**走
// （不是各吸各的档），否则宽高比就掰弯了。
func coverPixelSizeCapped(w, h, scale float32, cap int) (int, int) {
	if w <= 0 || h <= 0 {
		// 量不出显示尺寸：**按原图走**（0×0 让 `GetSized` 退回 `Get`）。
		return 0, 0
	}
	if scale <= 0 {
		scale = 1
	}
	pw := int(w*scale + 0.5)
	ph := int(h*scale + 0.5)

	// **长边吸档，短边按比例跟**——不是两条边各吸各的。
	//
	// 两条边各吸各的会把宽高比掰弯：400×336 的两条边分别吸到 400 / 400，
	// 图被拉伸两成（这个仓库吃过这一口，`TestTheProbeKeyMatchesTheDrawnKey`
	// 里量出来的 400w_400h 就是它）。
	//
	// 而只吸长边、短边纯按比例算，又让短边**连续**变化（首页磁贴的宽随窗口
	// 走、高固定）：窗口拖一像素 URL 就换一个，实测拖动 64 个像素产生 48 个
	// 不同的 URL。
	//
	// 所以短边**跟比例、但量化到「1/8」**：宽高比的偏差最多 3%，肉眼看不出来
	// （而且画的时候 `Fit(ui.Cover)` 还会再裁一次），而拖动时短边只会每隔
	// 几十像素才变一档——`TestDraggingTheWindowDoesNotMakeNewURLs` 钉着这一条。
	//
	// ⚠️ **量化粒度是 1/8 而不是 1/32**（票 #624/#664）：1/32 那档的偏差太大——
	// 980 DIP 宽的横幅 @2x 要 1960×264，长边吸到 768 之后短边按比例是 103，
	// 量化到 32 的倍数变成 **128** ⇒ 比例偏 **19~24%**（横幅被拉宽，画面上
	// 看得见）。1/8 时短边落在 **264**（精确值）⇒ 偏差 **0%**。
	// 代价是首页磁贴拖 64 个像素产生的 key 从 3 个变成 7 个（那一档的判据
	// 按新口径重算过，见 `size_test.go`）。
	long, short := pw, ph
	if ph > pw {
		long, short = ph, pw
	}
	// ⚠️ **不再被 `maxStoredSide` 夹住**（票 #664）：那一条线是「**存进内存
	// 缓存的那一份**」的上限（`maxStoredSide` 的定义），它管不到「**向图床
	// 要多大**」这一头——两件事本来就不一样（图床给你 1000×1000、内存里存
	// 768×768），现在是被写成了一件。
	//
	// ⇒ 32MiB 那个内存预算**一个字都不变**：预算算的是 `bytesOf(bm)`（**解码后**
	// bitmap 的字节），而「存的那一份缩到 768」是 `scale.go` / `jpegstream.go`
	// 自己判的，与这里无关。
	tier := snapToTier(long)
	if cap > 0 && tier > cap {
		tier = cap
	}
	if long > 0 {
		short = quantize(int(float64(short)*float64(tier)/float64(long)), coverQuantStep)
	}
	if ph > pw {
		return short, tier
	}
	return tier, short
}

// coverQuantStep 是短边量化的粒度（像素）。
//
// ⚠️ **为什么是 8 而不是 32**：1/32 那档的**比例**偏差太大——980 DIP 宽的横幅
// @2x 要 1960×264，长边吸到 768 之后短边按比例是 103，量化到 32 的倍数变成
// **128** ⇒ 比例偏 **19~24%**（横幅被拉宽，画面上看得见）。1/8 时短边落在
// **264**（精确值）⇒ 偏差 **0%**。
//
// ⚠️ **代价**：首页磁贴那一格（宽随窗口走、高固定）拖 64 个像素产生的 key
// 从 3 个变成 **7 个**。⇒ 那一档的判据按新口径重算过（`size_test.go`）。
const coverQuantStep = 8

// quantize 把 px 量化到 step 的整数倍（向上取整，至少一个 step）。
//
// 它是「短边跟着长边的比例走，但不要精确到像素」——理由见 `coverPixelSize`
// 里那段注释：精确到像素的话，窗口拖一像素 URL 就换一个。
func quantize(px, step int) int {
	if px <= 0 {
		return step
	}
	return (px + step - 1) / step * step
}

// sizeTiers 是向图床要图的档位，从小到大。
//
// ⚠️ **必须是「向上取整到某一档」，不能直接拼任意数字**：显示尺寸会因为窗口
// 宽度差一两个像素（105 和 106），而那些都会变成不同的 URL——同一张封面被
// 下好几份、在内存里各占一块、画出来一模一样。
//
// 档位之间至少差 ~25%：这样「吸档」造成的浪费最多两成，而相邻两个显示尺寸
// 撞到同一档的机会很大（一屏十几行的高度本来就差不多）。
//
// ⚠️ **最大那一档是 6400**（票 #664）：980 DIP 宽的横幅 @2x 要 **1960** 物理
// 像素，而这一档表原来最大是 768 ⇒ 横幅被夹成 768，Retina 上只有 384 DIP 清晰度
// （糊 2.5 倍）。
//
// ⚠️ **为什么一路加到 6400**（不是 2048 也不是 3072）：档位表是「向上取整」，
// 所以**长边撞到某一档的上沿时就会少要一点**——
//
//	最大档 3072 → 最坏比例偏差 3.09%（宽 1868），宽度 >1536 DIP 全都「糊」
//	最大档 6400 → 最坏比例偏差 2.56%（宽  765），**一个宽度都不糊**
//
// ⇒ 6400 那一档让「要的那一档」在 600~1900 DIP 全段都够用。
// ⚠️ **代价是网络字节**：只有「宽到要 4096 以上」的那些格子会多要——
// 而**横幅那一档（980 DIP）落在 2048，不受影响**。
//
// ⚠️ **扩档位表不影响「拖窗口产生多少 key」**（实测三个候选表：最大 768 /
// 2048 / 1792+2048，首页磁贴拖 64 像素都是 5 个、横幅拖 124 像素都是 1 个）——
// 因为「吸档」的粒度是由**档位之间的相对间距**定的，加几档高档不改变低档那几档。
var sizeTiers = []int{64, 96, 128, 160, 200, 256, 320, 400, 512, 640, 768, 1024, 1280, 1536, 1792, 2048, 2560, 3072, 4096, 5120, 6400}

// snapToTier 把要的像素吸到 `sizeTiers` 里**不小于它**的那一档。
//
// 超过最大档就是最大档（调用方还会按 `maxStoredSide` 再夹一次）。
func snapToTier(px int) int {
	for _, t := range sizeTiers {
		if px <= t {
			return t
		}
	}
	return sizeTiers[len(sizeTiers)-1]
}

// sizedURL 给 B 站图床的封面地址拼上**按需裁剪**的参数。
//
// 三种情况原样返回（理由见 `size_test.go` 的 `TestTheSizedURLCarriesTheRequest`）：
// 不是 `/bfs/` 的地址、已经带过 `@` 的、以及尺寸量不出来的。
//
// ⚠️ **这是「同一个封面、多个缓存条目」的来源**：`url@96w_96h_1c.webp` 和
// `url@400w_400h_1c.webp` 是两个 key。这正是要的——列表行和歌单页各拿各的，
// 谁也不挤谁（见 `TestSizedCoversAreTheirOwnCacheEntry`）。
func sizedURL(src string, w, h int) string {
	s := FormatURLProtocol(src)
	if s == "" || w <= 0 || h <= 0 {
		return s
	}
	if !strings.Contains(s, "/bfs/") || strings.Contains(s, "@") {
		return s
	}
	return s + "@" + strconv.Itoa(w) + "w_" + strconv.Itoa(h) + "h_1c.webp"
}
