// 播放条左边第三段那三枚键（赞 / 收藏 / 评论）各自的**读数**（票 #701 起带数，
// 随后收成右上角小角标）。
//
// # 这一族和「播放量那一列」是两件事
//
// 播放量那一列折成「1.2万」（`list.PlayCountText`）——它地方宽，要的是「约数」。
// 这一族折成短档位（`list.CountText`），放在图标右上角当**角标**，地方一点也不宽。
//
// # 本票的形状：**按钮右上角的小角标**
//
// 上一版（PR #736）的角标贴在图形右上**外侧**：`Attach(AnchorTopRight,
// AnchorTopLeft)`，图标本体完整、数字整个悬在外面。
//
// 角标贴在图形盒子的右上外侧，图标本体保持完整，数字用播放条底色的小圆角块
// 承托。角标宽度随数字内容计算，不依赖文本节点的隐式宽度。
//
// 角标和数字都是**绝对定位**的，不占布局——
// 于是那一枚键的宽仍是 **32**（图形 18 + 两侧各 7），和没有数字时一模一样。
//
// # 🔴 缺口块的颜色 = 按钮底下那一块底
//
// 缺口要「看着是挖的、不是贴的」，它的颜色就得和**数字底下的实际背景**逐像素
// 一致——错一档就是「图标上贴了块补丁」。播放条的底是
// `coverWash(t.Background)`（随封面取色微染，`playbar.go`），所以缺口色由
// **调用方**传进来（`countBadge` 的 `bg`）——三个调用点都在播放条那一列里，
// 给的是同一个值。
//
// ⚠️ **悬停 / 按下不用跟着换色**：按钮的悬停淡底是 `flat.feel` 挂在按钮上的
// `DrawOver`（`mygo/ui/element.go` 的 `paintAfterFn`）——它画在**一切**（含缺口
// 块和数字）**之上**，于是缺口块和它的四周**同帧变深**，缝还是看不见。如果缺口
// 色自己再叠一遍悬停色，反而会画出「缺口比旁边深一档」的方块。
//
// # 🔴 角标不占布局，但它照样登记命中
//
// 框架的绝对定位元素绘制时排在普通子元素**之后**（`mygo/ui/paint.go` 的两趟
// 循环）——所以缺口块画在图形**上面**。而它**照旧登记命中**
// （`mygo/ui/runtime.go`）——于是缺口块底下那一小块，按钮收不到指针事件。
//
// ⇒ 所以缺口块必须 **`PassThrough()`**：它不读屏、不点、不吃悬停——它是「图形
// 右上角挖出来的一个缺口」，不是一枚键。`nav-feed` 那个红点（`navbar_feed.go`
// 的 `viewDynamicDotMark`）是同一个形状、同一个理由。
//
// # 三枚键的**共性**（所以这里有一份共享的配方）
//
//	图形 18（`iconMd`）在一个 18×18 的盒子里，缺口块挂在这个盒子的右上角
//
// 角标折出来的字是 `list.CountText`（那一族的折法只有这一处），而**约束**
// （字号 / 颜色 / 缺口块的挂点与圆角 / PassThrough）在 `countBadge` 这一个
// 函数里——**三枚键共用**（赞键的图形那一块是绝对定位的两层，它自己拼盒子，
// 但**角标走同一份**）。
//
// # 🔴 「+」不许截：从「上限保险」换成「根本不设上限」
//
// 横排时代和外侧角标时代，数字格钉着一个**布局上限**（22.5）：那一格是「借来
// 的固定宽」，折法哪天改宽了，截断切的就是末尾、而「+」永远是最后一个字符。
//
// 缺口时代**没有那个上限**：缺口块随字长宽（`fitWidth` 走内容宽），字多宽缺口
// 就多宽——「+」**结构上截不掉**（没有给截断发生的格子）。`TestTheCountNeverLosesItsPlus`
// 的判据照旧：每一档单独画出来，墨迹都不许比字宽窄。
