// 这一族的几个尺寸。
//
// 🔴 **缺口块不占布局**：它 `Attach` 在图形盒子的右上角（`AnchorTopRight`），
// 是**绝对定位**的——所以「带不带数字」对那一枚键的宽**一个字都不差**：都是
// 32（图形 18 + 两侧各 7 的内边距）。
//
// ⚠️ **图形盒子是 18×18**，不是按钮的 32×32：缺口块挂在**图形**上（那是它读的
// 数的那一枚的身份），而不是按钮盒的角上——挂在按钮角上会跑出图形之外一整圈
// （7 的内边距），缺口就挖在按钮的右上角、而不是「图形右上」。
const (
	// playbarBadgeFont 是角标的字号（**固定 9，不乘系统文本缩放**）。
	//
	// 🔴 **为什么这一格不跟 `scale.Font` 走**（而界面别处的字都跟）：
	//
	// 「+」是这一族的**语义**（「至少这么多」）——而**截断切的是末尾，而「+」永远
	// 是最后一个字符**，所以「+」**总是第一个被切掉的**。实测（系统文本放大）：
	//
	//	scale 1.00  99k 墨迹 18  |  99k+ 墨迹 24  ✅ 「+」还在
	//	scale 1.25  99k 墨迹 23  |  99k+ 墨迹 17  ❌ 「+」被切
	//	scale 1.40  99k 墨迹 19  |  99k+ 墨迹 19  ❌ 「+」被切
	//	scale 2.00  99k 墨迹 13  |  99k+ 墨迹 13  ❌ 「+」被切
	//
	// ⇒ 而**分界线比 1.25 更早**（那张表是 10 号字那一版量的）：按字宽算，
	// scale 1.15 时 `99k+` 已经是 27.8（超当时的上限），`10k+` 25.7、`1亿+` 26.9
	// 也都超了——而 **125% / 150% 是 Windows 上的常见设置**。9 号字上限更宽、
	// 字更小，只会更装不下放大，结论不变。
	//
	// ⇒ 所以**这一格的字号钉死，不跟 scale 走**：字宽**恒定** ⇒ 任何 scale
	// 下都装得下。
	//
	// 🔴 **本票是 9，不是 10**：对照网易云实测（用户视觉审查），角标的字约是
	// 图标高的 1/3——18 的图形配 10pt 的数字太大、且和图标的视觉重量拉不开。
	// 收到 9（≈ 图标高的一半以下），数字才像「嵌在缺口里的读数」而不是
	// 「和图形并排的另一件东西」。
	//
	// # 🔴 **这个取舍的完整账**（票 #701 的审查，本票照旧成立）
	//
	// ## 代价（明摆着）
	//
	// **用户的系统文本放到 200% 时，这一格仍是 9 号，而旁边的歌名是 20 号**
	// ——**数字会比歌名小一半还多**。
	//
	// ⇒ 那是**有意**的取舍，**不是遗漏**。
	//
	// ## 为什么这么取舍（按优先级）
	//
	//  1. **「+」是语义**（「至少这么多」）——截掉它，「至少这么多」就变成
	//     「正好这么多」= **撒谎**。
	//  2. **数字是读数不是正文**（图形才是那一枚键的身份）——读数不跟正文
	//     缩放是**合理**的，不是将就；角标比正文小正是它该有的形状。
	//  3. **观感不一致是次要问题**，而且**只在放大到 115% 以上的用户那儿
	//     出现**（Windows 上 125% / 150% 是常见设置，但 115% 以下没问题）。
	//
	// ## 为什么没有第三条路
	//
	// **让这一格也放大、同时把上限也放大** ⇒ 角标是**绝对定位、不占布局**的，
	// 所以「装不下」不再是「把左列撑宽」——而是「角标那一格本身被截断」，而
	// **截断先切掉那个「+」**。⇒ 「+」会没，这一族**不许**。
	//
	// ⚠️ **别处的字照旧跟着 scale 走**：歌名、UP 名、别的读数——**只有这一格**
	// 不跟（理由见上）。
	playbarBadgeFont = 9
	// badgeNotchOut 是缺口块的上缘从图形盒子的上沿**往上探**多少（2）。
	//
	// 网易云那个缺口不是缩在图形框里面的：它包住图形的角——块的上缘越过图形
	// 上沿 2 像素，缺口下缘那段圆弧才落在字形上，看着是「图标被咬了一角」，
	// 而不是「图标里面挖了一块」。
	badgeNotchOut = 2
	// badgeNotchBite 是缺口块的左缘**收进图形右缘**多少（6）。
	//
	// 🔴 **缺口是咬在角上的，不是包住整个图形**：缺口块的左缘只收进图形
	// 右缘 6 像素——咬掉的是右上角那一小块（图形的右肩、上沿右端那截
	// 笔画），块的主体往右伸到图形**外面**的空气里、数字的主体也跟出去。
	//
	// 对照：如果让缺口块把整个字宽都收在图形上（宽字那一档「99k+」≈22 比
	// 图形 18 还宽），缺口会从图形右缘一路吃到左缘——实测那一档图形只剩
	// 下半截一撇，星标缩成「∧」、拇指剩个拐角，图标本身认不出来了。
	badgeNotchBite = 6
	// badgeNotchR 是缺口块的圆角。
	//
	// 缺口块的四个角都圆——**左下角**那个圆弧就是「咬进图形里」的那一口（其余
	// 三角都探在图形外的空气里，圆不圆没人看见）。5 ≈ 块高（12 上下）的
	// 一半再小一点：再圆缺口就成了个胶囊、左上缘退成一道弧线，咬的那一口
	// 反而没有「凹进去一块」的直感。
	badgeNotchR = 5
	// badgeNotchPadL / badgeNotchPadR 是缺口块在数字**左 / 右**各留的空隙。
	//
	// 🔴 **左 8、右 6，不对称**（视觉审查打回的那一笔）：缺口左缘那一边是
	// **咬进图形里**的——数字的起笔和图形的残笔只隔这一道缝，3 像素实测是
	// 「字身几乎顶在笔画上」（放大看比网易云那种「豁口里留一圈白」挤得多）。
	// 左边给到 8（咬的那一边多咬一点没关系，要的是数字和被咬的笔画之间有
	// 一眼能看到的底色缝）；右边探在空气里，6 就够。
	//
	// ⚠️ **缺口块宽跟着两边一起长**（`countBadge` 里 `textW + PadL + PadR`）——
	// 不是「盒子不变、字往右挤」。
	badgeNotchPadL = space.Px8
	badgeNotchPadR = space.Px6
	// badgeNotchMinW 是缺口块的**最小宽**。
	//
	// 缺口块随字长宽，但字很短的时候（「123」「1k+」之前的小数）块太小就缩成
	// 一个点、嵌不住「缺了一角」的形状。12 是「缺口还能读出是一个凹陷」的下限。
	badgeNotchMinW = 12
	// badgeNotchMinH 是缺口块的**最小高**。
	//
	// 9 号字的行高约 11——留一点垂直余量，缺口块盖住的那一截字形才比数字
	// 本身厚一圈（数字不是贴着缺口上下沿画的）。
	badgeNotchMinH = 12

	// playbarBadgeMaxW 是数字那一串字**实测能到多宽**的参考值（22.5）——
	// 它已经**不再当上限用**（缺口块随字长宽，不封顶），留它是因为测试拿它
	// 量「那一格画出来的墨迹」作对照（`isolatedInkWidth` / `scaledCellInks`）。
	//
	// 🔴 **22.5 是量出来的，不是随手取的**：`list.CountText` 折出来的几档
	// 实测（9 号字，macOS，`ui.Painter.MeasureText` 量得，约为 10 号字的 0.9）：
	//
	//	「9k+」  ≈16.2   「99k+」 ≈22.0  ← 最宽的那一档
	//	「10k+」 ≈20.4   「1亿+」 ≈21.2
	//
	// ⇒ 它是「刚好装下最宽那一档（99k+ ≈22.0）再加一点抗锯齿余量」的数。
	playbarBadgeMaxW = 22.5
)

// playbarCountText 是那个读数该显示的字。**空串 = 没有这个数**（不画）。
//
// ⚠️ **折法只有一处**（`list.CountText`）：这一族三枚键用的是**同一套**折法，
// 而它和播放量那一族的（`list.PlayCountText`）**不是同一个函数**——后者折成
// 「1.2万」，宽度差着一截。
func playbarCountText(n int64) string { return list.CountText(n) }

// countKeyLabel 是「图形 + 角标」那一枚键的无障碍名字。
//
// 角标是独立的视觉读数，按钮本身只保留动作名称，避免读屏和悬停入口被折算数字
// 撑长成一串不可扫描的标签。
func countKeyLabel(name string, _ int64) string {
	return name
}

// countKeyTip 是那一枚键的**悬停提示**（tip 是那一句本身）。
//
// ⚠️ **提示句里也要有那个数**：数字只画在画面上，指针停在别处时用户读不到它。
//
// ⚠️ **提示句要说清那个数是「整个稿件」的**（票 #701 的语义要求）：多 P 的视频
// 里放的是第 3 集，而显示的是整稿的数字——不说清的话，用户会以为那是「这一 P」
// 的。
//
// 🔴 **提示里给的是**完整数字**，不是画面上那个折过的字**（票 #701 的要求）：
//
//	画面上   「99k+」（9 号字最宽 ≈22.0，而角标那一格的上限是 22.5）
//	提示里   「整个稿件 99999」
//
// ⇒ 而「1亿+」那一档**更是必须这样**：那一档是**夸大的近似**（对 100000 那个数
// 说「至少 1 亿」**不成立**——理由见 `widgets/list/count.go` 的文件头），所以
// **只有完整数字**说得清那一档到底是多少。
//
// # 🔴 **为什么提示里给完整数字**（免得下一个人看到「超 80」就去砍数字）
//
// **理由一：那一处是用户唯一能看到精确值的地方。** 画面上那一格**必须**折
// （它只有 22.5 宽，而完整数字放不下——**那正是它要折的原因**），而提示那一格
// **没有那个限制**。⇒ 精确值在那儿，用户要精确值的时候有地方拿。
//
// **理由二：气泡换行不是破版。** 提示气泡的宽度上限是 `t.Space(80)`
// （`internal/ui/tooltip.go:317`），而**完整数字那一串确实超**：
//
//	「整个稿件 12345」      宽  99.98
//	「整个稿件 1234567」    宽 116.57
//	「整个稿件 123456789」  宽 133.92
//
// ⇒ **但基线本来就超**（在干净的 `origin/main` 上量的）：
//
//	「看这一首的评论」          宽  97.24
//	「把这一首放进收藏夹」      宽 125.02
//
// ⇒ 所以「超 80」是**既有现象**，**不是本票引入的**；而 `MaxWidth` 让它**换行**
// 而不是溢出——那是**两行提示**，不是破版。
//
// ⇒ **所以别去砍数字**：砍了就等于「为了不让提示换行，把精确值从唯一能看到它
// 的地方拿掉」。
func countKeyTip(name string, n int64, tip string) string {
	if n > 0 {
		return tip + "（整个稿件 " + strconv.FormatInt(n, 10) + "）"
	}
	return tip
}

// countBadge 是挂在**图形盒子右上角**的那枚**缺口角标**（三枚键共用）。
//
// ⚠️ **这一格的约束只有这一处**：收藏键和评论键走 `countKeyIcon`，而**赞键自己
// 拼图形盒子**（它那两层背景 + 拇指是绝对定位的，见 `like.go` 的 `likeButton`）
// ——但**角标走这里**，于是三枚键的「缺口块 / 挂点 / 字号 / 颜色 / PassThrough」
// **只有一份**。
//
// # 🔴 形状：一块底色圆角块（缺口）+ 嵌在里头的数字
//
//	Attach(AnchorTopRight, AnchorTopRight) 缺口块的右上角钉在图形盒子的右上角，
//	                                      再上探 / 右探各 `badgeNotchOut`
//	PassThrough()                          不登记命中（底下的按钮照点）
//
// 「挖空」是**盖**的：缺口块刷成**按钮底下那块底**的颜色（`bg`，调用方给），
// 图形右上角那一截字形笔画就被它盖住——视觉上图标缺了一角，数字居中画在缺口
// 上，坐在凹陷里。
//
// ⚠️ **绝对定位是相对父元素的 padding box**（`mygo/ui/element.go` 的 `Attach`
// 文档：「puts its point self on the point at of the parent's padding box」）——
// 而父元素是**图形盒子**（18×18），不是按钮（32×32）。挂在按钮上会多出 7 的
// 内边距，缺口就挖到按钮的角上去了，而不是「图形右上」。
//
// 🔴 **`bg` 必须是「数字底下的实际背景」**——播放条那一列的底是
// `coverWash(t.Background)`（封面取色染过的 `t.Background`），调用方在播放条
// 那一列里现算现传。缺口色错一档，「挖的」就成了「贴的」。
//
// ⚠️ **悬停 / 按下不跟着变**：按钮的悬停淡底是 `DrawOver` 画在一切之上（含缺口
// 块）——缺口和它的四周同帧变深，缝看不见；缺口自己再叠一层就画出深色方块了。
// 文件头《缺口块的颜色》那一节记着这笔账。
//
// 🔴 **必须 `PassThrough()`**：缺口块画在图形**上面**（绝对定位排在普通子元素
// 之后，`mygo/ui/paint.go`），而命中测试照旧登记它（`mygo/ui/runtime.go`）——
// 不 PassThrough 的话，缺口块底下那一小块按钮**点不动**（`nav-feed` 那个红点是
// 同一个形状、同一个理由：`navbar_feed.go` 的 `viewDynamicDotMark`）。
//
// ⚠️ **颜色是 `TextMuted`**：角标是**附属读数**，不是那一枚键的身份——图标才是。
// 它和播放条上别的次要读数（UP 名、时间）同一个色阶。
//
// 🔴 **数字没有宽度上限**：缺口块随字长宽（一行字、不包折），所以「+」**结构上
// 截不掉**——没有给截断发生的格子。这是从「上限 22.5 的保险」变成「不封顶」的
// 理由，见文件头《「+」不许截》那一节。
//
// ⚠️ **字号是**固定的**（`playbarBadgeFont`），不是 `scale.Font(c, …)`**——
// 理由见那个常量的注释（系统文本放大 125% 就会切掉那个「+」，而「+」是这一族
// 的语义）。
// badgeTextWidth 是「量出来的字宽」过一道兜底之后的宽度。
//
// 🔴 **`MeasureText` 量不到的时候不许把 0 传下去**（对抗性审查查出的一笔）：
// 字体后端还没就绪 / 量不到那一串时它回 0——而不挡的话，`notchW` 只剩
// 两侧 padding（14 ≥ `badgeNotchMinW`，**连最小小宽那道兜底都救不回来**），
// 更糟的是 `Text` 的 `MinWidth(0).MaxWidth(0)` 会把**整串数字裁成零宽**——
// 画面上剩一个空底色缺口，数字整个没了。⇒ 量不到就退回上限那一档
// `playbarBadgeMaxW`（缺口画宽一点，可数字一定画得出）。
//
// ⚠️ **它是单独一支函数，不是 `countBadge` 里的一行**——`MeasureText` 是
// `*ui.Context` 上的方法、mock 不掉，所以这条分支只能这样测：把「量出来的
// 值 → 兜底后的值」抽成一个纯函数，0 / 负数 / 正常宽三档各喂一遍。
func badgeTextWidth(measured float32) float32 {
	if measured <= 0 {
		return playbarBadgeMaxW
	}
	return measured
}

// countBadge 是图标键右上角的计数（原型 `.cnt`）：等宽 10 号 600、字距 -0.02em、次要色，
// 底是播放条的 `side` 色，内边距 2/4、圆角 6，离键上沿 1、右沿 -4（超出键 4）。
//
// 它挂在键里 18×18 的图形盒子上（盒子在 36×36 的键里居中，盒子右上角在键的 (27, 9)），
// 所以相对盒子右上角是「往右 13、往上 8」。dx 是长按三连时图标的抖动偏移，计数跟着抖。
func countBadge(c *ui.Context, n int64, _ ui.Color, dx float32) {
	t := playbarCountText(n)
	if t == "" {
		return
	}
	p := tok.Of(c.Theme())
	textW, _ := c.MeasureText(0, ui.Span{Text: t, Size: playbarBadgeFont, Weight: 600})
	badgeW := max(textW+space.Px4, float32(badgeNotchMinW))
	ui.Box(c).Key("count-badge-notch").
		Attach(ui.AnchorTopRight, ui.AnchorTopLeft).
		Top(-10).Right(-2).Translate(dx, 0).
		Width(badgeW).Height(12).
		Radius(tok.R6).Background(p.Side).Padding(space.Px1, space.Px2).
		PassThrough().
		Children(func() {
			typo.Mono(ui.Text(c, t)).FontSize(8).FontWeight(600).LetterSpacing(-0.2).
				TextColor(p.Text2).SingleLine()
		})
}

// countKeyIcon 是计数键里的图形盒子（18×18，图形居中）+ 右上角的计数。
// on 是「开着」（收藏了 / 赞了）：图形 accent-text；平时次要色，悬停正文色。
func countKeyIcon(c *ui.Context, iconName string, hovered, pressed bool, n int64, bg ui.Color) {
	countKeyIconOn(c, iconName, hovered, pressed, false, n, bg)
}

func countKeyIconOn(c *ui.Context, iconName string, hovered, pressed, on bool, n int64, bg ui.Color) {
	ui.Box(c).Size(iconMd, iconMd).Children(func() {
		ic := ui.Icon(c, icon(iconName)).FontSize(iconMd).
			Attach(ui.AnchorCenter, ui.AnchorCenter).TextColor(pbIconColor(c, hovered, on))
		flat.PressScale(ic, pressed, false)
		countBadge(c, n, bg, 0)
	})
}
