// 播放条左边第三段那三枚键（赞 / 收藏 / 评论）各自的**读数**（票 #701）。
//
// # 这一族和「播放量那一列」是两件事
//
// 播放量那一列折成「1.2万」（`list.PlayCountText`）——它地方宽，要的是「约数」。
// 这一族折成「1k+ / 10k+ / 99k+ / 1亿+」（`list.CountText`）——它**地方一点也不宽**：
// 900 宽的窗口上左边那一列离进度条滑块只剩 7.7 像素（票 #682 量出来的），
// 而三枚键都要带着各自的数。
//
// 🔴 **宽度恒定是功能正确性，不是排版偏好**（票 #216 那个坑）：中间那一列是
// `PassThrough` 的（它自己那一个框不接指针），但它的**子节点**照旧登记命中，
// 于是左列撑出轨道的那一截上的键会被进度行那一块的命中框盖住——**点不动，
// 而画面上看不出坏了**。
//
// # 三枚键的**共性**（所以这里有一份共享的配方）
//
//	图形 18（`iconMd`）│ 缝 2 │ 数字 10 号字（`scale.Size10`）
//
// 数字那一格的**折法**是 `list.CountText`（那一族的折法只有这一处），而
// **约束**（字号 / 颜色 / 宽度上限 / 省略号）在 `countText` 这一个函数里。
//
// ⚠️ **字号是 `Size10`**：这是播放条上最小的一档（全应用没有更小的正文），
// 而数字是**附属信息**（图形才是那一枚键的身份）。
//
// # 🔴 两个口径（别把它们混起来）
//
//	**字宽**  那一串字本身有多宽（`ui.Painter.MeasureText` 量得）——它**随平台
//	         字体变**，所以不是个能拿来钉死的数。
//	**上限**  数字那一格**最多占多宽**（`playbarCountMaxW` = 24.5）——它是**布局**
//	         的数，而布局的数**必须是常数**。
//
// ⇒ **宽度账按「上限」算，不按「字宽」算**：左列的保底宽（`playbarLeftMinW`）
// 是一个**常数**，而字宽不是——按字宽算的话，换一个字体保底宽就变了，
// 「多一 P 那一档和单 P 那一档一样宽」那条就破了。
//
// ⚠️ **900 宽下的余量是 5.20**（实测，左列右沿 325.5 / 滑块左沿 330.7）——
// **按上限算**。而按**字宽**算（某一档的字实测有多宽）会是另一个数——那个数
// 只对**这一个平台的这一个字体**成立。
//
// 🔴 **而那 5.20 是「视觉间距」，不是碰撞缓冲**：`MaxWidth` 在**布局层**硬夹住
// （实测字宽 90.71 时那一格仍恒是 24.50），所以**左列的宽是常数、碰撞不可能
// 发生**。那 5.20 是**留给人眼**的。
package ui

