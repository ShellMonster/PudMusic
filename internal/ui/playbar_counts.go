// 播放条左边第三段那三枚键（赞 / 收藏 / 评论）各自的**读数**（票 #701 起带数，
// 本票起收成**角标**）。
//
// # 这一族和「播放量那一列」是两件事
//
// 播放量那一列折成「1.2万」（`list.PlayCountText`）——它地方宽，要的是「约数」。
// 这一族折成「1k+ / 10k+ / 99k+ / 1亿+」（`list.CountText`）——它挂在图标的
// 右上角当**角标**，地方一点也不宽。
//
// # 本票的形状：**角标，不是横排**
//
// 改之前是「图形 18 │ 缝 2 │ 数字」横排（`countKeyRow`）：数字占一格，带数字的
// 那一枚键因此宽 44.5——900 宽的窗口上左列右端离进度条滑块只剩 5.20 像素
// （票 #682 / #701 量出来的）。那是「地方不够」被逼出来的形状。
//
// 现在改成**网易云式**：数字折成一个小字角标，**左缘贴图形右缘、上缘贴图形
// 上沿**——`Attach(AnchorTopRight, AnchorTopLeft)` 把角标的左上角摆在图形盒子的
// 右上角（数字整个在图形右上**外侧**，不压住图标本体、也不往角里收）。角标是
// **绝对定位**的，不占布局——
// 于是那一枚键的宽回到 **32**（图形 18 + 两侧各 7），和没有数字时一模一样。
//
// ⇒ 三枚键各窄 12.5，第三段从 165.5 缩回 **137**（四枚 32 + 三道 3 的键间缝）
// ——**净让 28.5 像素给了进度条**（`playbarLeftMinW` 的宽度账见 `playbar.go`）。
//
// # 🔴 角标不占布局，但它照样登记命中
//
// 框架的绝对定位元素绘制时排在普通子元素**之后**（`mygo/ui/paint.go` 的两趟
// 循环）——所以角标画在图形**上面**。而它**照旧登记命中**（`mygo/ui/runtime.go`）
// ——于是角标那一小块底下，按钮收不到指针事件。
//
// ⇒ 所以角标必须 **`PassThrough()`**：它不读屏、不点、不吃悬停——它是「粘在图形
// 右上角的一串字」，不是一枚键。`nav-feed` 那个红点（`navbar_feed.go` 的
// `viewDynamicDotMark`）是同一个形状、同一个理由。
//
// # 三枚键的**共性**（所以这里有一份共享的配方）
//
//	图形 18（`iconMd`）在一个 18×18 的盒子里，角标挂在这个盒子的右上角
//
// 角标折出来的字是 `list.CountText`（那一族的折法只有这一处），而**约束**
// （字号 / 颜色 / 宽度上限 / 省略号 / PassThrough / 挂点）在 `countBadge` 这一
// 个函数里——**三枚键共用**（赞键的图形那一块是绝对定位的两层，它自己拼盒子，
// 但**角标走同一份**）。
//
// # 🔴 两个口径（别把它们混起来）
//
//	**字宽**  那一串字本身有多宽（`ui.Painter.MeasureText` 量得）——它**随平台
//	         字体变**，所以不是个能拿来钉死的数。
//	**上限**  角标那一格**最多占多宽**（`playbarBadgeMaxW` = 22.5）——它是**布局**
//	         的数，而布局的数**必须是常数**。
//
// ⇒ 上限是 **22.5**（量出来的：9 号字下折法最宽的那一档「99k+」≈22.0，刚好
// 装下——理由见 `playbarBadgeMaxW` 的注释），而**「+」不许被截掉**那条铁律
// 原样保留：截断切的是末尾，而「+」永远是最后一个字符。
//
// ⚠️ **上限管的是「角标自己的那一格」**，不是「它伸出去多远」：角标挂在图形
// 右上角，宽出来的那一截伸到图形**右上方的空气里**（按钮上面、右边那枚键的
// 左上），那是视觉余量，**不进任何一列的宽度账**——所以 22.5 不再挤左列。
package ui

import (
	"strconv"

	"github.com/ShellMonster/PudMusic/internal/ui/widgets/flat"
	"github.com/ShellMonster/PudMusic/internal/ui/widgets/list"
	"github.com/egoist/mygo/ui"
)

// 这一族的几个尺寸。
//
// 🔴 **角标不占布局**：它 `Attach` 在图形盒子的右上角（`AnchorTopRight`），
// 是**绝对定位**的——所以「带不带数字」对那一枚键的宽**一个字都不差**：都是
// 32（图形 18 + 两侧各 7 的内边距）。
//
// ⚠️ **图形盒子是 18×18**，不是按钮的 32×32：角标挂在**图形**上（那是它读的
// 数的那一枚的身份），而不是按钮盒的角上——挂在按钮角上会跑出图形之外一整圈
// （7 的内边距），角标就悬在按钮的右上角、盖住悬停淡底，而不是「图形右上」。
const (
	// playbarBadgeFont 是角标的字号（**固定 9，不乘系统文本缩放**）。
	//
	// 🔴 **为什么这一格不跟 `scale.Font` 走**（而界面别处的字都跟）：
	//
	// 「+」是这一族的**语义**（「至少这么多」）——而**截断切的是末尾，而「+」永远
	// 是最后一个字符**，所以「+」**总是第一个被切掉的**。实测（系统文本放大）：
	//
	//	scale 1.00  99k 墨迹 18  |  99k+ 墨迹 24  ✅ 「+」还在
	//	scale 1.25  99k 墨迹 23  |  99k+ 墨迹 17  ❌ 「+」被切
	//	scale 1.40  99k 墨迹 19  |  99k+ 墨迹 19  ❌ 「+」被切
	//	scale 2.00  99k 墨迹 13  |  99k+ 墨迹 13  ❌ 「+」被切
	//
	// ⇒ 而**分界线比 1.25 更早**（那张表是 10 号字那一版量的）：按字宽算，
	// scale 1.15 时 `99k+` 已经是 27.8（超当时的上限），`10k+` 25.7、`1亿+` 26.9
	// 也都超了——而 **125% / 150% 是 Windows 上的常见设置**。9 号字上限更宽、
	// 字更小，只会更装不下放大，结论不变。
	//
	// ⇒ 所以**这一格的字号钉死，不跟 scale 走**：字宽**恒定** ⇒ 任何 scale
	// 下都装得下。
	//
	// 🔴 **本票是 9，不是 10**：对照网易云实测（用户视觉审查），角标的字约是
	// 图标高的 1/3——18 的图形配 10pt 的数字太大、且和图标的视觉重量拉不开。
	// 收到 9（≈ 图标高的一半以下），数字才像「挂在图形上的小尾巴」而不是
	// 「和图形并排的另一件东西」；同时「99k+」从 24.49 收到 ≈22，键与键之间
	// 留得出可辨的缝（理由见 `playbarBadgeMaxW`）。
	//
	// # 🔴 **这个取舍的完整账**（票 #701 的审查，本票照旧成立）
	//
	// ## 代价（明摆着）
	//
	// **用户的系统文本放到 200% 时，这一格仍是 9 号，而旁边的歌名是 20 号**
	// ——**数字会比歌名小一半还多**。
	//
	// ⇒ 那是**有意**的取舍，**不是遗漏**。
	//
	// ## 为什么这么取舍（按优先级）
	//
	//  1. **「+」是语义**（「至少这么多」）——截掉它，「至少这么多」就变成
	//     「正好这么多」= **撒谎**。
	//  2. **数字是读数不是正文**（图形才是那一枚键的身份）——读数不跟正文
	//     缩放是**合理**的，不是将就；角标比正文小正是它该有的形状。
	//  3. **观感不一致是次要问题**，而且**只在放大到 115% 以上的用户那儿
	//     出现**（Windows 上 125% / 150% 是常见设置，但 115% 以下没问题）。
	//
	// ## 为什么没有第三条路
	//
	// **让这一格也放大、同时把上限也放大** ⇒ 角标是**绝对定位、不占布局**的，
	// 所以「装不下」不再是「把左列撑宽」——而是「角标那一格本身被截断」，而
	// **截断先切掉那个「+」**。⇒ 「+」会没，这一族**不许**。
	//
	// ⚠️ **别处的字照旧跟着 scale 走**：歌名、UP 名、别的读数——**只有这一格**
	// 不跟（理由见上）。
	playbarBadgeFont = 9
	// playbarBadgeMaxW 是角标那一格**最宽**多少（22.5）。
	//
	// 🔴 **22.5 是量出来的上限，不是随手取的**：`list.CountText` 折出来的几档
	// 实测（9 号字，macOS，`ui.Painter.MeasureText` 量得，约为 10 号字的 0.9）：
	//
	//	「9k+」  ≈16.2   「99k+」 ≈22.0  ← 最宽的那一档
	//	「10k+」 ≈20.4   「1亿+」 ≈21.2
	//
	// ⇒ **22.5 是「刚好装下最宽那一档（99k+ ≈22.0）再加一点抗锯齿余量」的数**。
	//
	// 🔴 **上限不许低于它**：**截断切的是末尾，而「+」永远是最后一个字符**——
	// 「+」**总是第一个被切掉的东西**，而「+」是这一族的语义（「至少这么多」，
	// 没了就是撒谎）。⇒ 最宽的那一档必须本身就装得下上限，一档都不许靠截断
	// 兜底（理由同 10 号字那一版的实测，见 `widgets/list/count.go` 的文件头）。
	//
	// ⚠️ **和改之前（横排那一版）的差别**：那时这个上限挡的是「字变宽把左列
	// 撑宽」——左列是常数，而角标**不占布局**，所以它现在挡的只有「角标那一格
	// 自己被截断」这一件事（结果一样：那个「+」不许没）。
	playbarBadgeMaxW = 22.5
)

// playbarCountText 是那个读数该显示的字。**空串 = 没有这个数**（不画）。
//
// ⚠️ **折法只有一处**（`list.CountText`）：这一族三枚键用的是**同一套**折法，
// 而它和播放量那一族的（`list.PlayCountText`）**不是同一个函数**——后者折成
// 「1.2万」，宽度差着一截。
func playbarCountText(n int64) string { return list.CountText(n) }

// countKeyLabel 是「图形 + 角标」那一枚键的**无障碍名字**。
//
// 🔴 **数字不许只靠画面传达**（读屏软件看不见它）：拿到数的时候名字里带上它。
//
// ⚠️ **没有数字时名字就是那两个字**（一字不多）：拿不到数（离线 / 还没回来 /
// 本地文件）的时候画面上也没有数字——那时候多说一句「赞 0」是在撒谎。
//
// ⚠️ **它必须是「图形 + 角标」那一枚的名字，而不是那个数字自己**：这一枚键的
// **身份是图形**（图标对辅助技术不可见，`mygo/ui/svg.go`），而数字是读数。
func countKeyLabel(name string, n int64) string {
	if t := playbarCountText(n); t != "" {
		return name + " " + t
	}
	return name
}

// countKeyTip 是那一枚键的**悬停提示**（tip 是那一句本身）。
//
// ⚠️ **提示句里也要有那个数**：数字只画在画面上，指针停在别处时用户读不到它。
//
// ⚠️ **提示句要说清那个数是「整个稿件」的**（票 #701 的语义要求）：多 P 的视频
// 里放的是第 3 集，而显示的是整稿的数字——不说清的话，用户会以为那是「这一 P」
// 的。
//
// 🔴 **提示里给的是**完整数字**，不是画面上那个折过的字**（票 #701 的要求）：
//
//	画面上   「99k+」（9 号字最宽 ≈22.0，而角标那一格的上限是 22.5）
//	提示里   「整个稿件 99999」
//
// ⇒ 而「1亿+」那一档**更是必须这样**：那一档是**夸大的近似**（对 100000 那个数
// 说「至少 1 亿」**不成立**——理由见 `widgets/list/count.go` 的文件头），所以
// **只有完整数字**说得清那一档到底是多少。
//
// # 🔴 **为什么提示里给完整数字**（免得下一个人看到「超 80」就去砍数字）
//
// **理由一：那一处是用户唯一能看到精确值的地方。** 画面上那一格**必须**折
// （它只有 22.5 宽，而完整数字放不下——**那正是它要折的原因**），而提示那一格
// **没有那个限制**。⇒ 精确值在那儿，用户要精确值的时候有地方拿。
//
// **理由二：气泡换行不是破版。** 提示气泡的宽度上限是 `t.Space(80)`
// （`internal/ui/tooltip.go:317`），而**完整数字那一串确实超**：
//
//	「整个稿件 12345」      宽  99.98
//	「整个稿件 1234567」    宽 116.57
//	「整个稿件 123456789」  宽 133.92
//
// ⇒ **但基线本来就超**（在干净的 `origin/main` 上量的）：
//
//	「看这一首的评论」          宽  97.24
//	「把这一首放进收藏夹」      宽 125.02
//
// ⇒ 所以「超 80」是**既有现象**，**不是本票引入的**；而 `MaxWidth` 让它**换行**
// 而不是溢出——那是**两行提示**，不是破版。
//
// ⇒ **所以别去砍数字**：砍了就等于「为了不让提示换行，把精确值从唯一能看到它
// 的地方拿掉」。
func countKeyTip(name string, n int64, tip string) string {
	if n > 0 {
		return tip + "（整个稿件 " + strconv.FormatInt(n, 10) + "）"
	}
	return tip
}

// countBadge 是挂在**图形盒子右上角**的那枚角标（三枚键共用）。
//
// ⚠️ **这一格的约束只有这一处**：收藏键和评论键走 `countKeyIcon`，而**赞键自己
// 拼图形盒子**（它那两层背景 + 拇指是绝对定位的，见 `like.go` 的 `likeButton`）
// ——但**角标走这里**，于是三枚键的「挂点 / 字号 / 颜色 / 上限 / PassThrough」
// **只有一份**。
//
// # 🔴 形状：绝对定位、不占布局、不读屏、不吃指针
//
//	Attach(AnchorTopRight, AnchorTopLeft) 角标的左上角钉在图形盒子的右上角（外侧）
//	PassThrough()                         不登记命中（底下的按钮照点）
//
// ⚠️ **绝对定位是相对父元素的 padding box**（`mygo/ui/element.go` 的 `Attach`
// 文档：「puts its point self on the point at of the parent's padding box」）——
// 而父元素是**图形盒子**（18×18），不是按钮（32×32）。挂在按钮上会多出 7 的
// 内边距，角标就悬在按钮的右上角、盖住悬停淡底，而不是「图形右上」。
//
// 🔴 **必须 `PassThrough()`**：角标画在图形**上面**（绝对定位排在普通子元素
// 之后，`mygo/ui/paint.go`），而命中测试照旧登记它（`mygo/ui/runtime.go`）——
// 不 PassThrough 的话，角标底下那一小块按钮**点不动**（`nav-feed` 那个红点是
// 同一个形状、同一个理由：`navbar_feed.go` 的 `viewDynamicDotMark`）。
//
// ⚠️ **颜色是 `TextMuted`**：角标是**附属读数**，不是那一枚键的身份——图标才是。
// 它和播放条上别的次要读数（UP 名、时间）同一个色阶。
//
// 🔴 **`MaxWidth` + `MaxLines(1)` + 省略号**：宽度账见 `playbarBadgeMaxW` 的
// 注释——**当前折法一档都不截**（最宽的「99k+」≈22.0 ≤ 上限 22.5），而上限本身
// 是**保险**：折法哪天改宽了，它挡住「角标那一格自己被截断」——截断先切末尾，
// 那个「+」就没了，而「+」是这一族的语义。
//
// ⚠️ **字号是**固定的**（`playbarBadgeFont`），不是 `scale.Font(c, …)`**——
// 理由见那个常量的注释（系统文本放大 125% 就会切掉那个「+」，而「+」是这一族
// 的语义）。
func countBadge(c *ui.Context, n int64) {
	t := playbarCountText(n)
	if t == "" {
		// ⚠️ **没有数字时这一格不画**：角标连建都不建（占一个绝对定位的孩子是
		// 小事，但「没有数」和「零个赞」是两件事——见 `TestTheThreeCountsNeverShowZero`）。
		return
	}
	ui.Text(c, t).FontSize(playbarBadgeFont).
		TextColor(c.Theme().TextMuted).
		// 🔴 **MinWidth 不许少**：`Attach` 里框架按父盒子的 padding box（18×18）
		// 给可用宽，而 `fitWidth` 取 `min(内容, 可用)`——不钉 MinWidth 的话，
		// 角标那一格被夹成 18，「1亿+」就被截成「1亿…」，**那个「+」没了**
		// （它是这一族的语义）。钉到上限那一档，一格都不截。
		MinWidth(playbarBadgeMaxW).MaxWidth(playbarBadgeMaxW).
		// ⚠️ **字左对齐**：角标那一格钉成上限宽、左缘钉在图形右缘——窄的那
		// 一档靠左让**字的左缘贴着图形右肩**，宽窄几档左端都落在同一个点上。
		TextAlign(ui.Start).
		MaxLines(1).Ellipsis("…").
		// 🔴 **角标的左上角钉在图形盒子的右上角、一点都不挪**——
		// `Attach(AnchorTopRight, AnchorTopLeft)`：左缘=图形右缘、上缘=图形
		// 上缘。实测教训：往左收 1.5（`Right(1.5)`）「9k+」的 9 就压回拇指肚
		// 上；往下压 2.5（`Top(2.5)`）数字中线就落到图标中线、看着是「居中」
		// 不是「贴上沿」。网易云那个形状是**左缘贴右缘、上缘贴上沿**——
		// 数字整个在图形右上外侧，图形完整露出。
		Attach(ui.AnchorTopRight, ui.AnchorTopLeft).
		// 🔴 **不吃指针**：它是「粘在图形右上角的一串字」，不是一枚键——底下的
		// 按钮照点，悬停照常。
		PassThrough()
}

// countKeyIcon 是「图形盒子 + 角标」那一枚里的**图形那一块**（收藏 / 评论共用）。
//
// # 🔴 结构：一个 18×18 的盒子，图形在盒子里，角标挂在盒子右上角
//
// 改之前图形是「行里的一个 18 宽的孩子」，数字是它右边的一格。现在图形回到
// **和没有数字时一模一样的形状**：18×18 的盒子（`iconMd`），而角标**不占布局**
// ——所以这一枚键的宽是 32，**带不带数字都一样**。
//
// ⚠️ **盒子是给角标当锚的**：`Attach` 相对**父元素的 padding box**——所以角标
// 要挂在**一个正好 18 宽**的盒子上，它的右上角才是图形的右上角（挂在按钮上
// 会多出 7 的内边距，角标就悬到按钮角上去了）。
//
// ⚠️ **悬停变主色**（`flat.IconAccentOnHover`）：和相邻几枚一样（上游
// `hover:text-primary`）——而 `flat.Button` 只会铺一层淡底，图形自己不换色的话
// 悬停反馈就只剩那层淡底。
//
// ⚠️ **按下缩放**（`flat.PressScale`）：纯图标键才缩，而这一枚是「图标 + 角标」
// ——图形缩、角标不缩（角标缩了会跟着抖，读数不该动）。
func countKeyIcon(c *ui.Context, iconName string, hovered, pressed bool, n int64) {
	ui.Box(c).Size(iconMd, iconMd).Children(func() {
		// 图形在盒子的正中（`Attach` 是相对盒子的 padding box 居中）。
		ic := ui.Icon(c, icon(iconName)).FontSize(iconMd).
			Attach(ui.AnchorCenter, ui.AnchorCenter)
		if col, ok := flat.IconAccentOnHover(c, false, hovered); ok {
			ic = ic.TextColor(col)
		}
		flat.PressScale(ic, pressed, false)
		// 🔴 **角标挂在盒子右上角**——它是绝对定位的，不占布局，而它的父盒子
		// 是 18×18，于是右上角正好是图形的右上角。
		countBadge(c, n)
	})
}
