// 应用的语言：简体中文。
//
// ## 为什么菜单要专门管这件事
//
// 框架给自己的字符串（**菜单项**、系统文件框的按钮）只带着**英语**那一套
// （`mygo/internal/l10n/messages/en.json`）——别的语言要**应用自己把那个
// 语言包引进来**（`mygo/locales/zh-Hans`）。
//
// 而「这个应用是用什么语言写的」框架默认是**看应用自己的文案目录**
// （`i18n.Languages()`）——我们没有那个目录（界面上的字全是写死的中文），
// 于是它以为这个应用是英语的，菜单就全是英文：
// "Hide 布丁音乐" / "Quit 布丁音乐" / "Close Window" / "Edit" / "View"。
//
// 一个中文应用顶着一排英文菜单项，是最扎眼的一种不对——而这一栏是**应用
// 级的**，用户每一帧都看得见。
//
// 所以两件事一起做：
//
//  1. **把中文那一份引进来**（下面那个空导入）；
//  2. **告诉框架这个应用是简体中文写的**（`SetLanguages`）——菜单里那些
//     角色项的文案于是是中文（隐藏 布丁音乐 / 退出 布丁音乐 / 编辑 / 显示…）。
//
// ⚠️ **用的是 `SetLanguages` 而不是 `SetLocale`**：后者会把语言**存进系统**
// （macOS 上是应用的默认项，系统设置里看得到），而我们要的是「菜单是中文」，
// 不是「替用户改他的语言偏好」。`SetLanguages` 只是声明，一个字节都不写盘。
//
// ⚠️ **不引那个语言包的话，框架会自己在日志里点名**：
// 「the app is written in zh-Hans, but MyGo's own strings are in English there:
// import _ "github.com/egoist/mygo/locales/zh-Hans"」（`mygo/locale.go` 的
// `missingTranslations`）——连该引哪个包它都写出来了。
package ui

import (
	"github.com/egoist/mygo"

	// 简体中文那一份框架文案（菜单项、系统文件框的按钮）。
	//
	// ⚠️ **空导入也是必须的**：不引它，框架找不到中文那一份，菜单还是英文
	// （框架的日志会点名这件事，见文件头）。
	_ "github.com/egoist/mygo/locales/zh-Hans"
)

// installLanguage 告诉框架这个应用是用简体中文写的。
//
// ⚠️ **要在 mygo.App.Run() 之前调**：应用一开起来，框架就把语言定下来
// （`startLocale`），而菜单是**那之后**按那个语言重新贴一次文案的
// （`relabelMenus`）——所以这一句排在建菜单**之前或之后**都行，但排在
// `Run()` 之前是必须的（`Run()` 之后语言就定下来了）。
//
// ⚠️ **在别处调它没用**：框架的 `SetLanguages` 是「应用级」的，这一层
// （界面层）只是替应用说一声——真正生效的是 `mygo.App` 那一个实例。
func installLanguage() {
	mygo.App.SetLanguages("zh-Hans")
}

// resolveLanguageNow 把应用的语言**现在就**定下来。
//
// ⚠️ **只能在主线程上调**：它走的是 `App.Locale()`，而那一条要**在主线程上**
// 把语言算出来（框架的 `onMainValue`）——不在主线程上时它会**一直等下去**
// （无头 Tester 里没有事件循环，那条路等不到，测试会挂到超时）。
// 生产路上它在 `main()` 里（`ui.Run`），主线程 ✓。
//
// 为什么要「现在就」：菜单是紧接着建的，而框架贴角色文案用的语言是「应用
// **此刻**显示的语言」——应用还没开起来时那一份还是空串，于是建菜单那一刻
// 拿到的是英文。框架自己会在开起来之后把**有角色**的那几项重新贴一遍
// （`relabelMenus`），但**它只认有角色的项**：框架默认编辑菜单里那个「语音」
// （`roleSubmenu` 里写死的文案、**没有角色**）就永远是英文的——实测真机：
// 编辑菜单里夹着一个 "Speech"，而它底下那两项却是中文的
// 「开始讲话 / 停止讲话」。
//
// ⚠️ **为什么不用 `SetLocale`**：那一条会把语言**存进系统**（macOS 上是应用的
// 默认项，系统设置里看得到），而且**每次启动都会把用户自己选的语言覆盖回
// 我们的**——那是替用户改偏好，不是「这个应用是中文的」。
func resolveLanguageNow() {
	_ = mygo.App.Locale()
}
