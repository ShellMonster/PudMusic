package ui

import (
	"math"
	"time"
)

// 迷你播放器那个「歌词卷帘」的**弹簧**（票 #307）。
//
// # 它为什么是一个自己积分的弹簧，而不走框架那条 `ui.Animation`
//
// 旧版是**定时长曲线**（240ms + `motion.Unified`）——放下去是一段匀速的
// 滑，收起来也是同一段。而用户 2026-10-27 给的参考
// （<https://qinggan.geekaso.com> 左侧那个卷轴）要的是**卷轴展开**：
// 放得快、到底后**回弹两三下、幅度递减**；收起像手卷上去，**不弹**。
//
// ⇒ 展开那一段必须**欠阻尼**，而那一段是「一扇窗长高」——过冲意味着窗高
// 短暂地超过目标，而那一帧**窗比内容高**，透明的那一块就在吃点击
// （`minicurtain.go` 文件头第 1 条）。⇒ 框架那条 `AnimateTo` 不够用
// （它的过冲我们控制不住），所以**自己积分**。
//
// # 积分式（照参考页那一套，一个字不差）
//
//	a = w²(target − p) − 2ζw·v      ← 回复力 + 阻尼
//	v += a·dt
//	p += v·dt
//
// `dt` 钳在 **0.05s**（参考页那一行 `Math.min((t-last)/1000, 0.05)`）：
// 机器卡一下（掉一帧）时 dt 不会一下子变得很大，弹簧不会「一步蹦过去」。
//
// # 停止条件
//
//	|target − p| ≤ 0.004 且 |v| ≤ 0.06
//
// （参考页那一行 `Math.abs(target-p)>0.004 || Math.abs(v)>0.06`。）
//
// # 🔴 镜像：过冲被翻成「回弹时略微缩回去一点」
//
// 展开时画出来的高度是 `vis = 1 − |1 − p|`：
//
//   - `p ≤ 1`（还没到顶）⇒ `vis = p`；
//   - `p > 1`（过冲了）⇒ `vis = 2 − p`，**比 1 小**。
//
// ⇒ **画出来的高度永远 ≤ 目标高度**。⇒ **窗高永远不会超过 84 + 236**
// ⇒ 「窗比内容高 ⇒ 透明那块吃点击」那条坑**不会回来**，而**回弹看得见**。
//
// ⚠️ **这就是「弹簧怎么不破那条」的全部答案**（票面 §②）：不是把过冲调小到
// 看不见，而是**过冲只发生在弹簧内部那个 `p` 上，画出来的那一帧仍然是
// ≤ 目标**。
//
// # 收起那一支不镜像
//
// `vis = max(0, p)`：目标 0 时 p 一路往 0 走，**没有过冲**（ζ = 1.1 过阻尼）
// ⇒ 高度一路缩，窗一路缩 ⇒ **每一帧窗高 == 内容高**。
//
// # 换目标时从「上一帧画出来的那一个高度」起步
//
// ⚠️ **参考页也是这么做的**（`panelSpring` 里 `let p=PanelFX.p`，而
// `PanelFX.p` 存的是**镜像之后**的值）——所以「展开到一半就收起」时，
// 收起是从**用户眼睛看到的那一个高度**开始的，不是从过冲的峰值开始的。
// ⇒ **不会突然跳一下**。

const (
	// miniCurtainOpenW / miniCurtainOpenZ 是**展开**那一段的弹簧参数。
	//
	// ⚠️ **ζ = 0.55 是欠阻尼**（< 1）⇒ 放到底之后**回弹两三下、幅度递减**。
	//
	// ⚠️ **w = 14 是按「约 150~180ms 到全开」反算出来的**（票面 §验收第
	// 一条）：照那套积分，60fps 下 `p` 越过 1 的时刻是 **167ms**（w = 12.5
	// 是 183ms / w = 16 是 133ms）——落在「150~180ms」那一档的正中间。
	//
	// ⚠️ **回弹幅度 25 像素左右**（236 的 11%）：这是 `ζ = 0.55` 的必然结果
	// （过冲 `p` 峰值 1.104 ⇒ `vis` 谷 0.898 ⇒ 缩回去 20 像素）。**这是
	// 「回弹看得见」和「窗高不超过目标」能同时成立的原因**：缩回去的是
	// **画出来的高度**，而窗高跟着它走——于是窗在那两三帧**真的矮了一点**，
	// 而**从不超过目标**。
	//
	// ⚠️ **别拿 w 往大了调**：w 越大回弹越快（回弹周期 ≈ 2π/w），幅度
	// 几乎不变（幅度只由 ζ 决定），而**到顶越快**——w = 16 只用 133ms 就到顶，
	// 那不是「放下去」，是「弹上去」。
	miniCurtainOpenW = 14
	miniCurtainOpenZ = 0.55

	// miniCurtainCloseW / miniCurtainCloseZ 是**收起**那一段的弹簧参数。
	//
	// ⚠️ **ζ = 1.1 是过阻尼**（> 1）⇒ **一路收回 84，中间没有过冲**——
	// 而「不弹」是票面 §验收第二条点名要的（参考页那边是 13 / 1.1，
	// 「临界阻尼」，同一档）。
	//
	// ⚠️ **收起比展开慢**（回复力小一点）：而这是**对的**——手卷上去
	// 本来就比放下来慢，而「不弹」比「快」更要紧。
	miniCurtainCloseW = 13
	miniCurtainCloseZ = 1.1

	// miniCurtainSpringEpsP / miniCurtainSpringEpsV 是**停止条件**那两个数。
	//
	// ⚠️ **它们是参考页那一行**（`Math.abs(target-p)>0.004 || Math.abs(v)>0.06`）
	// ——照抄是因为那两个数是「肉眼看不出差别」的那一档：再小一点，弹簧会
	// 多跑十几帧（而迷你窗是**失焦照画**的，那十几帧的分配是**一直**在付的，
	// 见 `framebudget_test.go`）；再大一点，卷帘停在离目标差半个像素的地方。
	miniCurtainSpringEpsP = 0.004
	miniCurtainSpringEpsV = 0.06

	// miniCurtainSpringMaxDT 是 dt 的钳位（0.05 秒）。
	//
	// ⚠️ **照参考页那一行**：机器卡一下（掉一帧）时 dt 不会一下子变得很大，
	// 弹簧不会「一步蹦过去」。
	miniCurtainSpringMaxDT = 0.05
)

// miniCurtainSpring 是卷帘高度那一段**自己积分的弹簧**。
//
// ⚠️ **它挂在 `Shell.miniCurtain` 里**（不是包级变量）：它是**每一扇迷你窗
// 一份**的状态，而迷你窗可以是两扇（两个外壳，见 `miniplayer.go` 的
// `openMiniPlayer`）。
type miniCurtainSpring struct {
	// p 是**弹簧内部那个位置**（可能 > 1：过冲就在这里）。
	p float64

	// v 是**速度**（单位：位置 / 秒）。
	v float64

	// pos 是**上一帧画出来的高度**（0~1）。
	//
	// ⚠️ **它管的是「换目标时从哪儿起步」**：展开到一半收起时，起点是**用户
	// 眼睛看到的那一个高度**，不是过冲的峰值——参考页也是这么做的
	// （`panelSpring` 里 `let p=PanelFX.p`，而 `PanelFX.p` 存的是镜像后的值）。
	pos float64

	// last 是**上一帧积分到哪儿了**（`time.Time`）。
	//
	// ⚠️ **它为什么存在**：弹簧是**按时间积分**的，而框架给的是「这一帧的
	// 时刻」（`c.Now()`）——两次积分之间隔了多久，得自己记。
	//
	// ⚠️ **换目标那一刻就要把它重记成那一刻**（`start` 做的事）：不然它记的
	// 还是**上一段动画**的末尾（可能是几分钟前），而那一下 `dt` 是几分钟，
	// 钳在 0.05 也还是**一大步**——弹簧会「啪」地一下蹦到目标的四成。
	last time.Time

	// moving 是「弹簧还在走没有」。
	//
	// ⚠️ **它是「还要不要下一帧」那个判据**：走完了就不该再要帧——迷你窗是
	// **失焦照画**的，多要一帧就是多一次整窗重建。
	moving bool

	// goal 是**这一段弹簧要去哪儿**（0 = 收着，1 = 展开）。
	//
	// ⚠️ **它跟 `miniCurtainState.target` 是两件事**：那一个是**像素**
	// （卷帘该有多高，236），这一个是**弹簧的目标位置**（0 或 1）。
	goal float64
}

// miniCurtainSpringStart 让弹簧**朝 goal 走**（换目标时也用它）。
//
// ⚠️ **换目标时从「上一帧画出来的高度」起步**，而**速度保留**（参考页那一套
// 也是这么做的：它把 `p` / `v` 存着，下一段接着用）。
//
// ⇒ 「展开到一半就收起」时，收起是从**用户眼睛看到的那一个高度**开始的
// ——**不会突然跳一下**。
func (sp *miniCurtainSpring) start(goal float64, now time.Time) {
	sp.goal = goal
	// ⚠️ **从上一帧画出来的那一个高度起步**（不是从过冲的峰值）——见上面。
	sp.p = sp.pos
	sp.moving = true
	// ⚠️ **积分的起点重记成「换目标那一刻」**（`now`）：不然它记的还是**上一
	// 段动画**的末尾（用户听了一首歌才又点开 ⇒ 那是几分钟前），而那一下
	// `dt` 是几分钟，钳在 0.05 也还是**一大步**：弹簧会「啪」地一下蹦到目标
	// 的四成（`v += w²·dt ≈ 9.8`，`p += v·dt ≈ 0.49`）——于是「放下去」变成
	// 「啪地一下出现」。
	//
	// ⚠️ **而记的是 `now`（换目标那一刻），不是零值**：零值会让下一帧的
	// `dt` 是「从零值到现在」——那一下被钳在 0.05（0.05 秒的一大步），而
	// 真实的一帧只有 16 毫秒 ⇒ **卷帘会跳一大截**。
	//
	// ⚠️ **记了 `now` 之后，下一帧照常积分**（`dt` = 那一帧的时刻 − 这一刻
	// 的时刻 ≈ 一帧）：**不多丢一帧**——丢一帧的话，「150~180ms 到全开」
	// 就变成了「166~196ms」。
	sp.last = now
}

// miniCurtainSpringReset 把弹簧**钉到 0** 并停掉它。
//
// ⚠️ **它用在「立刻收起」那一下**（设置开关被关掉 / 关窗 / 退出）：那几秒
// 窗马上就没了，滑下去的那一段是白滑的，而**更要紧的是「窗比内容高」**
// （文件头第 1 条）——中间那几帧窗是 320 高而内容只有 84，多出来的那一块
// 透明区在吃点击。
//
// ⚠️ **`pos` 也要归零**：它是「换目标时从哪儿起步」的那个高度——留着 1 的
// 话，下一次展开会**从满高起步**（一帧就到顶，没有展开的动作）。
func (sp *miniCurtainSpring) reset() {
	sp.p = 0
	sp.v = 0
	sp.pos = 0
	sp.goal = 0
	sp.moving = false
}

// miniCurtainSpringHold 把弹簧**钉在 goal 那一头**（一步都不动）。
//
// ⚠️ **它只给测试用**：帧预算那一档要量的是「**展开之后的稳态**」，而
// 走「点封面」那一条要一整套点击 + 推钟——直接钉住省事得多。
//
// ⚠️ **`started` 置 true**：钉住之后下一帧**照常积分**（而目标是它自己，
// 于是回复力是 0，速度也是 0——它一步都不动）。
func (sp *miniCurtainSpring) hold(goal float64) {
	sp.p = goal
	sp.pos = goal
	sp.goal = goal
	sp.v = 0
	sp.moving = false
}

// miniCurtainSpringStep 把弹簧往前推 dt，返回**画出来的高度**（0~1）。
//
// now 是**这一帧的时刻**（`c.Now()`）。
//
// ⚠️ **返回的是「画出来的高度」而不是 `p`**：过冲的那一段 `p > 1`，而画
// 出来的高度必须 `≤ 1`（镜像，见文件头那一节）。⇒ **调用方拿到的那个数
// 永远 ≤ 目标**，而窗高跟着它走 ⇒ 窗高永远 ≤ 84 + 卷帘高。
func (sp *miniCurtainSpring) step(now time.Time) float64 {
	dt := now.Sub(sp.last).Seconds()
	sp.last = now
	if dt <= 0 {
		// 钟没走（同一个时刻上跑了第二遍 view）：不积分。
		return sp.vis()
	}
	if dt > miniCurtainSpringMaxDT {
		dt = miniCurtainSpringMaxDT
	}
	w, z := miniCurtainSpringParams(sp.goal)
	// ⚠️ **回复力 + 阻尼**（参考页那一行，一个字不差）。
	a := w*w*(sp.goal-sp.p) - 2*z*w*sp.v
	sp.v += a * dt
	sp.p += sp.v * dt
	// ⚠️ **停止条件**（参考页那一行）。
	if math.Abs(sp.goal-sp.p) <= miniCurtainSpringEpsP && math.Abs(sp.v) <= miniCurtainSpringEpsV {
		sp.p = sp.goal
		sp.v = 0
		sp.moving = false
	}
	sp.pos = sp.vis()
	return sp.pos
}

// miniCurtainSpringParams 报「朝 goal 走」那一段的弹簧参数。
func miniCurtainSpringParams(goal float64) (w, z float64) {
	if goal >= 1 {
		// 展开：欠阻尼（回弹）。
		return miniCurtainOpenW, miniCurtainOpenZ
	}
	// 收起：过阻尼（不弹）。
	return miniCurtainCloseW, miniCurtainCloseZ
}

// vis 报**画出来的高度**（0~1）。
//
// ⚠️ **展开那一支是镜像**：`1 − |1 − p|`。
//
//   - `p ≤ 1` ⇒ `p`；
//   - `p > 1`（过冲）⇒ `2 − p`（**比 1 小**）。
//
// ⇒ 画出来的高度**永远 ≤ 1** ⇒ 窗高永远 ≤ 84 + 卷帘高 ⇒ 透明的那一块
// 永远不吃点击（文件头第 1 条）。而**回弹是看得见的**：那两三帧画出来的
// 高度真的矮了一点。
func (sp *miniCurtainSpring) vis() float64 {
	if sp.goal >= 1 {
		return min(max(1-math.Abs(1-sp.p), 0), 1)
	}
	return min(max(sp.p, 0), 1)
}
