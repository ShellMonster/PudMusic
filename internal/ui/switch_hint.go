// 开关拨动之后的那一句短提示：**效果看不见**的那几格才说。
//
// # 判据只有一条：**这一格的效果在界面上看不出来**
//
//   - **看不见的**（音量均衡、播放记录上报、开机自启）：界面上没有任何变化能
//     告诉用户「它生效了」——只能听一遍才知道、或者过一阵子才知道。
//   - **看得见的**（主题、显示样式、显示搜索历史、折叠侧栏、封面取色）：拨过去
//     画面就变了，用户自己看得见——**不用弹**，弹多了就是噪音。
//
// # ⚠️ **只有「打开」的时候才说**
//
// 这一句说的是「**开了它会怎样**」。关掉的时候说同一句就是错的（"太响的歌会压
// 下来"——已经关了）。关掉那一下的反馈是**旋钮弹回去**。
//
// # 句子的样子是**定死的**
//
// 这一张表就是全部：一句一行、以「格名：效果」的样子，不许每一格自己发挥
// （自己发挥的必然会长成一段话，而一段话没人读）。
//
// ⚠️ **「音量均衡」那一句为什么不是「轻声会被拉高」**：本地文件确实会把轻的
// 抬上去（`internal/service/audio/normalize.go`：已知峰值时抬，抬完不超过
// 0.98），但**在线流只压不抬**（没有整首峰值，抬增益可能削波，而这一层没有限幅
// 器）。用户多半听的是在线流，所以那句话说的是两种情形都成立的那一半。
package ui

import (
	"github.com/ShellMonster/Biu_Go/internal/notice"
)

// switchHint 是「效果看不见」的那几格，拨开之后要说的那一句。
//
// ⚠️ **键是那一行的标题**（设置页上摆着的那几个字），不是设置文件里的键名——
// 键名是给盘上用的（`pickSwitch` 的 `key` 那个参数），这里要的是**用户看到的
// 那一行叫什么**。
var switchHint = map[string]string{
	"音量均衡":     "音量均衡：太响的歌会压下来",
	"上报本机播放记录": "上报本机播放记录：B 站历史里能看见",
	"开机自启":     "开机自启：登录后会自动打开",
	// ⚠️ **「更新提醒」这一格的效果在界面上看不出来**（票 #559）：通知弹在
	// **系统的通知中心**里，而不在应用界面上——而那一格恰恰是「用户不在应用里
	// 时才弹」，所以拨开之后的那一瞬间界面上一个字都不会变。
	"更新提醒": "更新提醒：有新版本时在通知中心里弹一条",
}

// saySwitchHint 弹那一句短提示。
//
// 格名不在表里（看得见的那些）就没有提示；关掉的时候也不说（理由见文件头）。
//
// **语气是 `notice.Plain`**（主色）：这是一句「告诉你接下来会怎样」的话，不是
// 「一件事办成了」（那才是 `Success`），也不是「出错了」（那是 `Danger`）。
func (s *Shell) saySwitchHint(title string, on bool) {
	if !on {
		return
	}
	text, ok := switchHint[title]
	if !ok {
		return
	}
	s.addToast(text, notice.Plain)
}
