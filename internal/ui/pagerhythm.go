// 页面节奏：内容区的横向边距、页标题的字号、Tab 的两种样子。
//
// # 这一份是「我们自己的」，不是「和 Biu 对齐」
//
// 上游那边也不干净：它的页容器是 `px-4`（16），行里再 `px-2`（8），所以内容
// 离内容区边缘是 **16 + 8 = 24**；而它自己的几页（搜索页的 `px-4`、设置页的
// `px-8`）也不是一个数。**这一票统一的是我们自己九页之间**，不是拿上游当
// 标尺——拿上游当标尺的那一条是 2026-10-15 用户拍板过的「内容区页边距比上游
// 大 4 像素」，见下面 `pagePadX` 那段。
//
// # 横向页边距取 20
//
// **不是随便挑的**：上游的内容离内容区边缘 24，我们的内容要离 **28**（比上游
// 多 4 像素，用户 2026-10-15 拍板过的那一条）。而**行自己那 8 像素的内边距
// 留着**（`widgets/list` 的 `cardPadX`、列表页的 `listPadX`），所以页容器
// 那一层要留的是 **28 − 8 = 20**。
//
// 换个数就一定会撞掉那条拍板：
//
//	页边距 16 → 内容离边缘 24（和上游一样，少了那 4 像素）
//	页边距 20 → 内容离边缘 28（**就是拍板过的那一个**）
//	页边距 24 → 内容离边缘 32（比拍板的多 8 像素）
//
// 而 20 恰好是我们**已经在用**的一个数（首页 / 下载记录 / 稍后再看 / 历史记录
// 四页都是它），所以这次统一只动三页：本地音乐（16 → 20）、搜索（28 → 20）、
// 收藏夹（24 → 20）。
//
// ⚠️ **设置页那一处不归这里**：它要收进居中的 900 宽那一栏（票 #127），横向
// 边距到时候由那一栏决定，不是这一页的页边距。
package ui

const (
	// pagePadX 是内容区左右各留多少像素。**七页共用这一个数**：
	// 首页 / 稍后再看 / 历史记录 / 本地音乐 / 下载记录 / 搜索 / 收藏夹。
	//
	// ⚠️ **用这个常量，不要写字面量**：七页各写各的数，过两个月又漂开——而
	// 「从首页点到本地音乐，内容区左右各退 4 像素」这件事在界面上看不出来，
	// 只有逐页量才量得出来。
	pagePadX = 20

	// pageTitleSize 是页标题的字号。**同一个数**。
	//
	// 为什么是 20 而不是 22：上游的 `h1` 是 `text-2xl`（24）、`h2` 是
	// `text-xl`（20），而 **22 不在 Tailwind 的刻度上**——它是某一页自己起的
	// 一个数，七页里有六页抄了它，于是「22 vs 20」就成了一种存在。20 是上游
	// 刻度上有的数（`text-xl`），而本地音乐那一页本来就已经是 20。
	//
	// ⚠️ **收藏夹那一页的大标题不走这个数**：它是 30（上游 `text-3xl`），见
	// `collectionTitleSize`——那一页有头图，标题是头图的一部分，不是页标题。
	pageTitleSize = 20

	// collectionTitleSize 是收藏夹 / 合集 / 系列那一页**头图区**的大标题。
	//
	// 抄上游 `pages/video-collection/header/index.tsx:85` 的 `text-3xl`（30），
	// 粗体。**它是唯一一个带头图的页面**，而头图区那个 22px 的标题和普通
	// 列表页的页标题一样大——200×168 的封面顶着一条 22px 的字，头重脚轻。
	//
	// ⚠️ **封面高度写死 168**（`collectionCoverH`），改完这个字号要确认**两行
	// 标题放得下**：30px 的两行约 72 高，加上简介 / 类型 / 创建者三行和间隙，
	// 整列约 148 高，还在 168 之内。
	collectionTitleSize = 30

	// smallCopyLeading 是小字的行高倍数。**1.5**——和列表行标题那个行距同一个
	// 数（`widgets/list` 的 `titleLeading`，那是 Tailwind 的默认行高）。
	//
	// ⚠️ **不写行高的话，这一行有多高是字体决定的**：同一个字号在不同字体下
	// 差几个像素，而那几像素会让「一行小字和旁边那一行齐不齐」变成看运气。
	smallCopyLeading = 1.5

	// smallCopyHintLeading 是 11px 那一处提示的行高倍数。**1.7**。
	//
	// ⚠️ **为什么比别处大一点**：11 × 1.5 = 16.5，而旁边 12px 的那些是 18——
	// 一行字的高度差两像素，弹窗里那几行看着就错开了。1.7 给到 18.7，和 12px
	// 的那些齐。
	smallCopyHintLeading = 1.7
)
