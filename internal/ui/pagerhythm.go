// 页面节奏：内容区的横向边距、页标题的字号、字重刻度、Tab 的两种样子。
//
// 数值的唯一目标值是仓库根的 `DESIGN.md`（票 #163 定的）。这一份只是把它
// 落成代码里的常量。
//
// # 横向页边距取 16，上下 0
//
// 上游的页容器是 `px-4`（16），**没有 `py`**；行里再 `px-2`（8），所以内容
// 离内容区边缘是 **16 + 8 = 24**。页容器那一层留 **16**，而不是把 24 直接写在
// 页面根上——后者会让页标题（它没有行内那 8 像素）比列表内容往里缩一截，
// 每一页的标题和下面的歌名对不齐。
//
// ⚠️ **这七页的页面根都没有上内边距**：上游没有 py，我们此前每页多出 16~28
// 的上边距（首页 / 下载记录 20、稍后再看 / 历史记录 / 本地音乐 16、搜索 28），
// 整块内容比上游低一截（票 #166 的 G40）。设置页和登录页同样收成 0。
//
// ⚠️ **设置页那一处不归这里**：它要收进居中的 900 宽那一栏（票 #127），横向
// 边距由那一栏决定，不是这一页的页边距。但它的**上**边距同样收成 0（G40）。
package ui

import (
	"github.com/ShellMonster/Biu_Go/internal/ui/widgets/space"
)

const (
	// pagePadX 是内容区左右各留多少像素。**七页共用这一个数**：
	// 首页 / 稍后再看 / 历史记录 / 本地音乐 / 下载记录 / 搜索 / 收藏夹。
	//
	// ⚠️ **用这个常量，不要写字面量**：七页各写各的数，过两个月又漂开——而
	// 「从首页点到本地音乐，内容区左右各退 4 像素」这件事在界面上看不出来，
	// 只有逐页量才量得出来。
	pagePadX = space.PageHorizontal

	// weightMedium 是 500 那一档字重（上游的 `font-medium`，用了 26 处）。
	//
	// **它是一档正经的字重，不是「介于 400 和 600 之间随便选」**：框架的
	// `FontWeight` 把 CSS 权重换算成 NSFont 的权重（`internal/text` 的
	// `nsWeight`），500 画出来比 400 明显粗、比 700 明显细。设置页的行标题
	// 用的就是它。
	weightMedium = 500

	// weightRegular 是 400 那一档字重（正文那一档）。
	//
	// ⚠️ **它不是为了给「默认就是 400」的地方起名字**：它是**量字高**的时候
	// 要**显式**写出来的那一档——`c.MeasureText` 的 `Span.Weight` 填 0 和
	// 填 400 出来的**行高差着一截**（实测认证那一行差 2.5 像素），而字高算
	// 错了就是「名字被顶进蒙版的淡区」（见 `upspace.go` 的 `upHeaderLineH`）。
	weightRegular = 400
)
