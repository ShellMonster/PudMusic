package ui

// 「正在取流」时绕在播放键外面转的那一圈光。
//
// # 挑的是哪一种：按钮外圈的转动光环
//
// 界面上表示「在等」的做法大致有五种，各自有各的场合：
//
//	均衡器条（equalizer bars）	几根竖条在跳。**说的是「正在响」**——
//					它长在歌名旁边（Spotify 那样），
//					意思是「这一首在放」。取流的
//					那一首**还没放起来**，拿它说
//					「在准备」是撒谎。
//	按钮变转圈（按钮就是一枚转圈）	最省地方，但**按钮没了**——用户按不了
//					暂停。票 #282 的评审明确否掉了
//					这一条（取流期间上一首还在放）。
//	呼吸 / 脉冲（按钮一亮一暗）	说的是「有反应了」，不说「在等」。
//					而且它没有方向感——用户不知道
//					它在等还是在退。
//	同心圆波纹（一圈圈扩出去）	雷达 / 声纳那一档，多见于「扫描中」。
//					在播放条这么紧凑的地方它太吵。
//	按钮外圈的转动光环	一圈光绕着按钮转。**说的是「在准备」**，
//					而且按钮**还在**、还是播放 / 暂停、
//					照样按得下。
//
// 这一票挑的是**最后一个**：用户 2026-10-25 说的正是它（「那种有一层光
// 还是什么的绕着播放按钮转圈那种 loading」），而它也是唯一一条**既说了
// 「在等」、又不把按钮拿走**的。
//
// ⚠️ **和票 #282 被否掉的那一条不是一回事**：那一票否的是「把按钮**换成**
// 一枚转圈」。这里按钮照旧（还是播放 / 暂停、还能按、提示照旧、禁用态
// 照旧），只是它**外面**多了一圈在转的光。
//
// # 上游 Biu 那边没有这一层
//
// 上游的播放条中间那一枚是 `components/music-play-control/index.tsx`：
// 一枚 `RiPlayCircleFill`（48），**没有**任何取流态的画法；而它整个
// 播放条上**一处**加载指示都没有（`layout/playbar/` 三个目录里没有
// Spinner）。所以这一层是**我们自己加的**，照的是行业做法而不是上游。
//
// # 对着参考量的那几个数
//
//	粗细	键的直径 × 0.07（播放条那一枚 3，满屏那一枚 4.5，迷你窗 2）
//	离键的缝	键的直径 × 0.12（播放条 5.3 / 满屏 7.7 / 迷你窗 2.9）
//	转过	100	度
//	一圈	1.4	秒
//
// 参考是 **Material 那一档的 indeterminate 圆形进度指示器**
// （`material-web.dev/components/progress/`）：它的容器是 48px、指示器
// （就是那一段弧）的粗细是**尺寸的 8.3333%**（48 的时候正好 4px）；
// 弧长在 0~50% 之间动，**平均 25%**（90°）；MUI / Material Web 那一族
// 转一圈是 **1.4 秒**（`CircularProgress.js` 的 `transform: rotate(0deg
// → 360deg)` 配 1.4s）。
//
// ⚠️ **粗细没有照抄 8.3333%**：那一档是给 48px 的**容器**看的，我们这个环
// 的外面还套着一枚实心强调色圆——照抄比例在播放条上是一道**粗杠**，而且和
// 键那一枚实心圆挨得太近，两团强调色糊在一起反而看不出在转。
//
// ⚠️ **缝（12%）是看着定的**：这一条没有参考，是按「两团同色的形状要分得
// 开」定的——太小了，光圈和那一枚实心圆读起来是**一个形状**（满屏那一枚
// 上尤其明显：底是糊过的封面，同色的两团挨在一起）。
//
// ⚠️ **转速也没有照抄**：1.4 秒一圈是 MUI 那一族的数，而 MyGo 自己那枚
// 转圈（`mygo/ui/indicators.go`）是 **900ms 一圈**（12 根辐条，每根
// 75ms）。取 1.4 秒是因为我们这个环比那枚 12px 的转圈大得多——环的周长
// 是它的十几倍，同样快的转速在这里看着是「一圈光在跑」，而不是「在转」。
//
// ⚠️ **颜色走主题令牌**：光圈是 `t.Accent`——**和键那一枚实心圆同一个
// 颜色**（不是另挑一个色）。理由：这一圈光说的是「**这一枚正在准备**」，
// 而键的颜色是「**这一枚是主键**」；两件事说的是同一枚键，所以是同一个
// 色。深浅两套都试过（出图见 `loadhalo_shot_test.go`），都读得出来。
//
// # 转的是哪三枚
//
//	播放条中间那一枚	**要**（44×44 的实心强调色圆）。这是用户说的那一处。
//	满屏播放器那一枚	**要**（64×64）。⚠️ **满屏那一档本来一个字都不说
//				在取流**（那里没有「正在取流」那一行），
//				所以这一圈光是那儿**唯一**的取流提示。
//	迷你播放器那一枚	**要**（24 的实心圆）。⚠️ **迷你窗里也只有这一圈
//				光**——那一扇窗只有歌名和音量两行，
//				同样一个字都不说在取流。
//
// ⚠️ **迷你窗那一枚的尺寸和别的不一样**：它的点击区是 28，而**画出来的
// 那枚圆是 24**（`flatIconButton` 的图形边长）——光圈绕的是**画出来的那
// 枚圆**，不是那个点击区。
//
// # 「第三行那句话」**留着**
//
// 光圈是**即时反馈**（余光就能看见「在准备」），那句话是**说明**（是哪一
// 首、卡在哪一步、等了多久）——两者说的不是一回事，所以都留。
//
// ⚠️ **它们不叠在一起**：光圈在中间那一列（播放键边上），那句话在左边
// 那一列的第三行，两者隔着大半个屏幕（出图见 `loadhalo_shot_test.go` 的
// 「整条播放条」那一张）——所以**不吵**。
//
// ⚠️ **第三行自己还有一枚 12 的转圈**（框架的），于是取流的时候画面上有
// **两处**在动。留着是因为：那一枚是**行内**的（它和那句话在一行，读起来
// 是「这句话在转」），光圈是**行外**的（它在键上，读起来是「这一枚在准备」）。
// 两者说的还是两件事。
//
// # 光圈画在键自己的那一层（`Draw`），不是另建一个元素
//
// 另建一个元素就得把它和键**并排**摆（键的盒子是那个实心圆，光圈比它
// 大一圈，画在键**里面**会被键的盒子裁掉），而并排就得套一层盒子——
// 盒子的 `Children` 回调每一帧要分配一次，而播放条那一档的每帧分配上限
// 只剩 2 次余量（`framebudget_test.go`）。
//
// 画在键自己的 `Draw` 里就没有这个代价：**不取流的时候那一档的分配一个
// 都不涨**（回调是取流的时候才挂上去的；实测：平时 14 次，取流那一档
// 58 次，而那 58 次里有 57 次是第三行那枚转圈的——光圈自己只多 **1** 次，
// 见 `loadhalo_test.go` 的 `TestTheHaloCostsAlmostNothingPerFrame`）。
//
// ⚠️ **代价是「键被禁用的时候不能画」**：框架对禁用的控件是整个乘 0.5
// 不透明度（`mygo/ui/paint.go:209-212`），而半透明的那一笔会走**软件**
// 路径（`StrokePolyline` 只在不透明的时候走 GPU 那一档）——于是光圈会
// 暗一半、还慢得多。所以**键是灰的时候不画光圈**：那一档本来也没有歌可
// 放（播放条左边连封面都不画，票 #222），而「正在取流：<歌名>」那一
// 句话还在（第三行）。
//
// # 角度是**画的时候**算的
//
// 这一圈光是**逐帧动**的，而它走的是「只重绘、不重建」那一档
// （`p.After`，票 #392 治的正是「每帧重建整棵界面」那个毛病）。所以
// 角度只能**画的时候**算——建的时候算出来的角度会被冻在闭包里，光圈
// 于是不转了（`like.go` 那个点赞进度环是同一个道理，见它那儿的注释）。
//
// ⚠️ **起点是「这一轮取流开始的那一刻」，不是「这一帧」**：播放条每
// 50ms 重建一次（应用层那个 tick），每帧都拿「此刻」当起点的话，光圈
// 每 50ms 就跳回 12 点——那是在抖，不是在转。所以起点记在壳上
// （`s.halo.start`）。
//
// # 慢的时候（票 #220 的「取流很慢」）光圈**不变**
//
// 光圈说的是「**还在准备**」，那句话说的是「**准备得慢**」。慢不是错，
// 这一档也**没出错**——所以光圈既不换色（换成警告色等于说「出错了」）、
// 也不变慢（变慢读起来像「快好了」）、也不停（停了读起来像「完了」）。
// 让它照旧转，慢不慢由那句话说。
//
// # 「减少动态效果」开着的时候不画
//
// 那一圈光**就是**动效本身：留一个不动的圈在键边上，用户只会以为那个
// 键被选中了。而「正在取流：<歌名>」那句话还在（播放条那一档；第三行），
// 信息没丢。
//
// # 为什么没有复用票 #468 的那一套旋转
//
// 票 #468（BMG-256，「满屏播放器的封面转起来」）走的是「**每帧推进一个
// 角度 + `AnimatePose`**」：pose 那一条通道**只重绘帧、不重建 view**，而
// 通道的目标是**建的时候**写死的——它从当前值走向那个目标，走到了就停。
// 于是「一直转」要靠**定期重建**把目标一次次往前推（#468 靠的是应用层
// 那个 50ms 的 tick，而**取流的时候那个 tick 未必在跑**——还没在放）。
//
// 这一圈光是**一段弧**（100°），不是一整枚元素：pose 只能转**整个**元素，
// 要从一枚转着的元素里得到一段弧，得靠 conic 渐变——而渐变的头尾是**建
// 的时候**定死的，亮的那一头不会跟着尾巴跑。
//
// 所以这里的角度是**画的时候按钟算的**（`p.Now()` 减起点），走的是
// `like.go` 那个点赞进度环的同一档机制（票 #392 立的：逐帧动的东西**只
// 重绘、不重建**）。它的代价是**零次 view 重建**——播放条那一档的每帧
// 分配预算一点没动（14 次，和改之前一样）。
//
// ⚠️ **等 #468 合进来之后**：两边可以并成一个共用的「转」的类型（角度
// 怎么推进、推进多少），曲线和那几个数都放在
// `internal/ui/widgets/motion` 里（#468 已经把满屏封面那一族的数放在
// 那儿了）。这一票**没有**去动那个包：#468 还在 `work/256` 分支上没合进
// main，而把那一张的提交并进这一票的分支，会让**两张票的 PR 撞车**——
// 先合的那张会让后合的那张变成空 PR，票就关不掉了。

import (
	"math"
	"sync/atomic"
	"time"

	"github.com/ShellMonster/Biu_Go/internal/app"
	"github.com/egoist/mygo/ui"
)

// 光圈的那几个数（对着参考量的理由见文件头那一节）。
//
// ⚠️ **粗细和缝都是按「键的直径」算的**，不是写死的两个像素：同一圈光在
// 播放条那一枚（44）和满屏那一枚（64）上是**同一个比例**，于是两处的视觉
// 份量一样——写死的话，满屏那一枚上的光圈会**细得看不出来**。
const (
	// loadHaloWidthRatio 是光圈那一段的粗细 = 键的直径 × **0.07**。
	//
	// ⚠️ **不是 Material 那一档的 8.3333%**：那一档是给 48px 的**容器**看的
	// （4px @ 48），而我们这个环的外面还套着一枚实心强调色圆——照抄比例是
	// 一道粗杠，两团强调色还会糊在一起。
	loadHaloWidthRatio = 0.07
	// loadHaloGapRatio 是光圈的内沿离键那一枚的圆边 = 键的直径 × **0.12**。
	//
	// ⚠️ **这 12% 是看着定的**：太小了，光圈和那一枚实心圆会读成**一个形状**
	//（满屏那一枚上尤其明显——底是糊过的封面，同色的两团挨在一起）。
	loadHaloGapRatio = 0.12
	// loadHaloSpan 是光圈转过多少度。**100** 度。
	loadHaloSpan = 100.0
	// loadHaloPeriod 是一圈多久。**1.4 秒**。
	loadHaloPeriod = 1400 * time.Millisecond
	// loadHaloSteps 是弧上取多少个点。
	//
	// ⚠️ **16 是够的**：播放条那一枚的中线半径 28，100° 分成 16 段是每段
	// 4.9 像素，而那一笔粗 3——接缝被圆头盖住，看不出是一段一段的。
	loadHaloSteps = 16
	// loadHaloFrame 是光圈多久要下一帧。**16 毫秒**（约 60 帧）。
	//
	// ⚠️ **用 `p.After` 而不是 `p.AnimationFrame`**：后者要的是「下一帧
	// 马上来」，而框架的 Tester 会**一直画到这一屏不再要帧**（最多二十
	// 帧）——于是「一帧」这个单位被摊薄，量出来的每帧成本会小得离谱
	// （`framebudget_test.go` 里有这道检查）。`p.After` 是「过 16 毫秒
	// 再画」，框架自己的转圈（`mygo/ui/indicators.go`）走的就是它。
	loadHaloFrame = 16 * time.Millisecond
)

// loadHaloWidth 是光圈那一段的粗细（键的直径是 box）。
//
// ⚠️ **有下限 2**：迷你窗那一枚只有 24，按比例算出来是 1.68——那是一根
// **发丝**，在 84 高的窗里几乎看不见。
func loadHaloWidth(box float32) float32 { return max(2, box*loadHaloWidthRatio) }

// loadHaloRadius 是光圈**中线**的半径（键的直径是 box）。
func loadHaloRadius(box float32) float32 {
	return box/2 + box*loadHaloGapRatio + loadHaloWidth(box)/2
}

// loadHalo 是这一圈光的状态。
//
// ⚠️ **只有起点这一个字段**：角度是画的时候按钟算的（见文件头），而
// 起点得记着——播放条每 50ms 重建一次，每帧都拿「此刻」当起点的话光圈
// 每 50ms 就跳回 12 点。
type loadHalo struct {
	// start 是这一轮取流从哪一刻起的。**零值 = 现在没有在取流**。
	start time.Time
}

// loadHaloOn 报「这一帧要不要画那一圈光」，顺便把这一轮的起点记下来。
//
// enabled 是「播放键那一枚是不是可点的」：键是灰的时候不画（理由见文件
// 头「光圈画在键自己的那一层」那一段）。
//
// ⚠️ **不用的时候要把起点清掉**：取流结束之后下一轮要**从 12 点重新转**
// （而不是接着上一轮的位置转半圈）。
func (s *Shell) loadHaloOn(c *ui.Context, st app.State, enabled bool) bool {
	if !st.Loading || !enabled || c.Preferences().ReduceMotion {
		s.halo.start = time.Time{}
		return false
	}
	if s.halo.start.IsZero() {
		s.halo.start = c.Now()
	}
	return true
}

// withLoadHalo 给播放键套上「正在取流」时绕着它转的那一圈光。
//
// b 是已经建好的那一枚播放 / 暂停键；box 是它的边长（实心圆的直径）。
//
// ⚠️ **它不建新元素**：光圈画在键自己的 `Draw` 里（理由见文件头）。
func (s *Shell) withLoadHalo(c *ui.Context, b ui.Element, st app.State, box float32, enabled bool) ui.Element {
	if !s.loadHaloOn(c, st, enabled) {
		return b
	}
	radius := loadHaloRadius(box)
	width := loadHaloWidth(box)
	start := s.halo.start
	// ⚠️ **那个开关是「活的」，所以取的是**指针**不是值**：画的时候问它才
	// 知道窗口这一刻看不看得见（`presence` 那一条路会改它，见 presence.go）。
	visible := s.visibleFlag()
	return b.Draw(func(p *ui.Painter, r ui.Rect) {
		s.drawLoadHalo(p, r, radius, width, start, visible)
	})
}

// drawLoadHalo 画这一帧的那一圈光。
//
// r 是键那一枚的盒子；radius 是光圈中线的半径；width 是那一段的粗细；
// start 是这一轮的起点；visible 是「这一扇窗现在看不看得见」那一个开关。
//
// ⚠️ **角度是画的时候按钟算的**（理由见文件头「角度是画的时候算的」）。
func (s *Shell) drawLoadHalo(p *ui.Painter, r ui.Rect, radius, width float32, start time.Time, visible *atomic.Bool) {
	// 从 12 点起、顺时针（和 CSS 的 `conic-gradient` 一个方向）。
	deg := math.Mod(p.Now().Sub(start).Seconds()*360/loadHaloPeriod.Seconds(), 360)
	cx, cy := r.X+r.W/2, r.Y+r.H/2
	// ⚠️ **这个数组在栈上**：`StrokePolyline` 只读它（不存），所以它不逃逸
	// ——每一帧分配一次的话，播放条那一档的分配预算就顶到了。
	var pts [loadHaloSteps + 1][2]float32
	for i := range pts {
		a := (deg + loadHaloSpan*float64(i)/loadHaloSteps) * math.Pi / 180
		pts[i] = [2]float32{
			cx + radius*float32(math.Sin(a)),
			cy - radius*float32(math.Cos(a)),
		}
	}
	// ⚠️ **不透明**：半透明的那一笔会走软件路径（`StrokePolyline` 只在
	// 不透明的时候走 GPU 那一档），而这一段弧每一帧形状都不一样——软件
	// 路径每一帧都要重新栅格化一个掩码。
	p.StrokePolyline(pts[:], width, p.Theme().Accent)
	// 下一帧：光圈在动 → 要一帧。而那一帧走的是**局部重绘**
	// （`p.After`，不是 `c.AnimationFrame()`）：光圈是画出来的，
	// 而局部重绘那一帧**只重画、不重建整棵元素树**（票 #392）。
	//
	// ⚠️ **窗口看不见就别再要下一帧**：那一帧看不见的窗口里空转，是
	// 满屏封面那一族的老毛病（票 #392）。
	if visible.Load() {
		p.After(loadHaloFrame)
	}
}
