package ui

// 逐帧分配预算（票 #156 那一组里的一条）。
//
// # 这条测试量的是什么
//
// 「界面变慢了只能靠人感觉」——而**时间**类的判据在这台机器上会被负载淹没
// （AGENTS §2：不要用固定帧数 / 固定毫秒当判据）。所以这里量的是**分配**：
//
//	每帧分配多少次 · 每帧分配多少字节 · 每帧存活堆涨多少 · 每帧建了几遍
//
// **分配次数不受机器快慢影响**：它是「这一帧建了多少个对象」的计数，不是
// 「建它们花了多久」。机器忙一点慢一点，这个数是同一个——满载的 CI 上跑
// 出来也是同一个数。
//
// # 从五个界面，五条上限起步
//
// 最早只覆盖最常用的五个（首页列表 / 播放条 / 队列抽屉 / 满屏播放器 / 稍后再看网格），
// 不全量。
// 全量的意思是「每一个界面都有一条预算」，那要等这些界面的画法稳定下来再说。
//
// （现在是十二档：票 #339 往后加了「稍后再看网格」，票 #284 往后加了「设置开关」
// 和「迷你播放器」那两档，票 #280 往后加了「迷你播放器歌词卷帘」，票 #573
// 往后加了「评论页」，票 #631 往后加了「关注页」和「下载记录页」，票 #684
// 往后加了「评论页·筛选开着」——见下面那一条。）
//
// # 「隔离的那一块」和「整窗」是两处，量的不是同一件事
//
//   - **分配预算**在**隔离**里量：只画那一块（`withView`），不画整窗。理由是
//     **归因**——整窗的分配里混着侧栏、顶栏和别的页面，超了以后报不出
//     「是哪一块多分配的」，而那条信息正是要它的人需要的。
//   - **「一帧建了几遍」**在**整窗**里量：「一帧建两遍」坏的是**两个调用方
//     都建了它**（满屏开着的时候抽屉由满屏那一支建，`viewMain` 必须让开），
//     隔离起来就看不见那一半了。
//
// # 那两档要放歌的界面，**不放真音频**
//
// 播放条和满屏播放器喂的是一份**手摆的状态**（`budgetState`），不是真放一首
// 文件：真放的话解码器那条 goroutine 会在测量窗口里分掉一大笔（一次性缓冲，
// 实测约 130 KB），落在哪一帧还是随机的——那是**音频**的成本，却会让「这一帧
// 花了多少」由它决定，而判据要分得清「噪声」和「回归」。
//
// # 分配次数会飘 ±1，是怎么来的（票 #407）
//
// **分配次数是进程级的全局计数**（`runtime.MemStats.Mallocs`）：**界面自己**
// 分的和**别的线程**分的，在测量窗口里是**分不开**的。而窗口是
// `after.Mallocs - before.Mallocs`（见 `measureFrames`）——**落在窗口里的
// 都算数**。
//
// 票 #407 实测（那一档的基线当时是 137；改过之后是 46，现象一样）：
//
//   - **逐帧量**：连续两万帧，**19999 帧都恰好是基线那个数**，只有 1 帧多
//     了一次（138 / 47）；
//   - **整窗量**：60 轮独立的 100 帧，59 轮是 13700 次，**1 轮是 13701**。
//
// ⚠️ **那多出来的一次就在测量窗口之内**（不是窗口之外）——所以窗口的均值是
// 137.01 而不是 137.00（`%.0f` 打出来还是「137」）。**「窗口之外」那个说法
// 是错的**：窗口就是 `after - before`，窗口里的每一笔都进这个数。
//
// ⚠️ **它不是界面画的**：把 `imgcache.glyphOf` 那次分配去掉之后它照样出现；
// 而**界面什么都不画**时（只画一个空盒子）同样的现象也出现——那一轮窗口是
// 1 次而不是 0 次。所以它是**进程里别的东西**（别的 goroutine，或者 runtime
// 的一次性工作）在窗口内分的一次。
//
// ⚠️ **它也不是 GC**：那一帧前后 GC 次数没变；而窗口里插一次 `runtime.GC()`，
// 分配数**一个不多**（这一轮 GC 自己零分配）。
//
// ⚠️ **所以「上限只比基线多 1」不是「紧」，是「没有余量」**：它拦不住任何
// 东西（那多出来的一次就能把它顶到上限），却会让**别的那张票**的「加压复验
// 3 遍全绿」偶发不成立（票 #219 的评审撞见过）。这一组的上限因此都按
// 「**基线 + 一截余量**」定，而余量要**大于那 ±1**。
//
// # 每一档的数在「冷跑」和「热跑」之间不一样
//
// **同一个进程里第一遍跑某一档是「冷」的，第二遍起是「热」的**——而整包跑、
// CI 跑看到的都是**热的那一组**。实测（票 #721，2026-11-01，**填上那份每帧
// 缓存之后**——理由见下面那一段）：
//
// | 档 | 冷跑（第一遍） | 热跑（第二遍起） |
// |---|---|---|
// | 首页列表 | 54 次 / 1420 字节 | 54 次 / 1420 字节 |
// | 播放条 | 22 次 / 553 字节 | 22 次 / 553 字节 |
// | 队列抽屉 | 39 次 / 560 字节 | 39 次 / 560 字节 |
// | 满屏播放器 | 50 次 / 1781 字节（T4 改版后，旧版 39 次 / 1556 字节） | 50~51 次 / 1781~1850 字节 |
// | 稍后再看网格 | 56 次 / 760 字节 | 56~57 次 / 765~868 字节 |
// | 设置开关 | 9 次 / 152 字节 | 9 次 / 152 字节 |
// | 迷你播放器 | 57 次 / 1217 字节（T5 改版） | 57 次 / 1217 字节 |
// | 迷你播放器歌词卷帘 | 76 次 / 1849 字节（T5 改版） | 76 次 / 1849 字节 |
// | 评论页 | 23 次 / 616 字节 | 23~24 次 / 616~654 字节 |
// | 评论页·筛选开着 | 23 次 / 616 字节 | 23~24 次 / 619~645 字节 |
// | 关注页 | 152 次 / 2593 字节（T3 改版重测） | 152 次 / 2593~2600 字节 |
// | 下载记录页 | 306 次 / 18064 字节 | 307~308 次 / 18102~18164 字节 |
//
// ⚠️ **这张表是票 #721 重测的**（2026-11-01）——而**这一票挪动了每一档的数**
// （不是只有满屏和播放条那两档）：因为**测量台之前每一帧都在重建整份 seam**
// （见下面那一段），而**填上缓存之后每一档都少建了一份**。
//
// ⇒ 所以各档的基线写的是「冷跑」那个数（它是**唯一能单独复现**出来的那个：
// `-run '.../首页列表'` 跑三遍都是同一个数），而**上限按「热跑」的
// 最坏那档定**——上限要盖住**所有跑法**，不然整包跑时就红。
//
// ⚠️ **别拿「冷跑那个数」当这一档的全部**：它比整包跑时看到的低一两次
// （几十字节）。评审要是拿整包跑的数去对注释里的基线，对不上是**预料之中**
// 的——对的是**上限**。
//
// # 🔴 **测量台自己也要享受那份每帧缓存**（票 #721）
//
// `pageInput()` 有一个**每帧缓存**（`page_inputs.go`）：这一帧里所有页面读到
// 的共享输入是**同一份**，而取一次要采**六个状态**——所以它**每帧取一次**就够。
//
// ⚠️ **而那份缓存是在 `Shell.View` 里填的**（`shell_view.go`）——于是
// **测量台把 `Shell.View` 整个换掉之后**（`withView`，`shelltest_test.go`）
// **那份缓存永远不命中**，**每一帧都重建整份 seam**。
//
// 实测（instrumented，`pageSeam()` 里数）：**改之前**每一帧重建的次数是
//
//	满屏播放器  20 次    评论页 / 评论页·筛选开着  10 次    播放条  2 次
//	其余各档      0 次
//
// （生产是 **1 次**——那一次在 `Shell.View` 里。）
//
// ⚠️ **而省掉重建之后，各档的数有涨有跌**（实测，见下面那张表）——而**方向
// 恰恰和直觉相反**：**重建次数最多的那几档（满屏 / 评论页）跌得最多**
//（满屏 153 → 39），**其余各档反而涨了五次到六次**。
//
// ⇒ **为什么涨**：那一档的页面**本来就在读共享输入**（`pageInput()`），而
// **兜底那条路每读一次就重建一份 seam**（六个状态：一次锁 + 一次值拷贝，各
// 一次）——**读几次就重建几次**。
//
//	改之前：页面读 N 次 ⇒ **重建 N 份 seam**（每份 6 次 / 96 字节）
//	改之后：页面读 N 次 ⇒ **命中缓存，零分配**
//
// ⇒ 而**改之前那一档量到的 N 次里，有一部分是那 N 份 seam 里的**——所以
// **读得越多（重建得越多）的那几档，省得越多**。
//
// ⚠️ **而「其余各档」为什么还涨了**：它们**本来重建 0 次**（页面**不读**
// 共享输入——首页列表、网格、迷你播放器、关注页、下载记录页都不读）——
// ⇒ 改之前它们**一分钱都不花在 seam 上**，而**改之后多了一次 `captureFramePage()`**
// （每帧一次：六个状态 = 6 次 / 96 字节）。
//
// ⇒ **那一次就是那五六次**——**不是回归**，而是**这一档在生产上一直要付的那
// 一次**（生产走 `Shell.View`，而那一路**一直**在取那一份）。
//
// ⚠️ **所以「涨了」的那几档，涨的正是生产上一直有的那笔**——**测量台之前
// 压根没付这一笔**（它走的不是 `Shell.View` 那条路），而**现在付了**。
//
// ⚠️ **这不是界面变慢了**——**生产上一直就是这些数**。⇒ **测量台之前量到的
// 是一台不存在的机器**（它每一帧重建，或者压根不取那一份），而**现在量到的
// 是用户看见的那一屏**。
//
// ⇒ **这一改挪动了每一档的数**（不是只有那两档）——所以**十二档的基线与上限
// 全部按实测重写**（票 #613 的纪律：「上限不能顺手改」——要单独立票：查清多出来
// 的字节是什么，要么让它便宜下来，要么**重测基线并写清新的数**）。
//
// # 与真窗口的帧耗时**不挂钩**
//
// 这里一个字都没量时间。真窗口一帧多少毫秒跟机器、跟显示器、跟后台负载都
// 有关系，是**另一张票**的事；而那条判据天生会在满载的 CI 上飘红，而它红的
// 时候和被测的逻辑一点关系都没有。这一条只数「建了多少」。
//
// # 为什么两条测试都开 ReduceMotion
//
// **因为 Tester 的钟站着不动**（框架的说明写在 `mygo/ui/headless.go`）：
// 凡是「动一下才到位」的东西——共享元素转场（满屏那个封面从播放条长过去）、
// 滑块的滑动、渐隐渐现——在 Tester 里**永远走不完**，于是那一帧会被反复画
// 二十遍（MyGo 的 Tester 一次 `Frame()` 最多画二十帧），「一帧」这个单位
// 就废了。
//
// `ReduceMotion` 是系统里本来就有的那个偏好（macOS 的「减弱动态效果」）：
// 开了它，框架让那些值**立刻到位**。它只改「值怎么过去」，不改「建了
// 什么」——所以它不会影响这一组要量的任何数，而它让「一帧就是一帧」成立。
//
// ⚠️ 真机上是用户自己开不开这个偏好的事；这里开它是为了让**测量的单位**
// 成立，不是为了让界面少动。

