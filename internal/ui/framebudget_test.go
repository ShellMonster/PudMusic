// budgetDownloadRows 造 n 行「下载记录」。
//
// ⚠️ **封面地址是空的**：有地址的话封面缓存会去拉，那是一条后台 goroutine，
// 又是一笔落在测量窗口里的噪声（理由同 `budgetLaterRows` 那一段）。
//
// ⚠️ **三种状态都有**（下载中 / 完成 / 出错）：真实的那一屏就是这样，而出错
// 那一格画得**最贵**（错误原因独占一行 + 一条红条）。只摆「完成」那一档量到
// 的是**最便宜**的那一屏。
func budgetDownloadRows(n int) []download.Snapshot {
	statuses := []download.Status{
		download.StatusRunning, download.StatusDone, download.StatusError,
		download.StatusPaused, download.StatusDone, download.StatusError,
		download.StatusDone, download.StatusPaused,
	}
	rows := make([]download.Snapshot, n)
	for i := range rows {
		rows[i] = download.Snapshot{
			ID:      fmt.Sprintf("BV1%d", i+1),
			Title:   fmt.Sprintf("第 %d 首歌", i+1),
			Label:   "无损 FLAC",
			Dest:    filepath.Join(dlDir, fmt.Sprintf("第 %d 首.m4a", i+1)),
			Status:  statuses[i%len(statuses)],
			Err:     "服务器不肯说这一条流有多长",
			Done:    int64(i+1) * 1024 * 1024,
			Total:   20 * 1024 * 1024,
			AddedAt: dlAddedAt,
			Percent: 50,
		}
	}
	return rows
}

// budgetDownloadsMount 挂上下载队列（下载记录页要它）。
//
// ⚠️ **走真队列文件那条路**：这一页的数据是**队列文件**读回来的，而那一趟
// （读文件 + 建任务）是**别的线程**的分配，不该算进界面的账里（理由同
// `budgetState` 那一段）。挂上之后 `rowsFn` 给的是那一份，而这一档量的是
// 「画一屏记录要多少」。
//
// ⚠️ **队列文件里是空的**：这一档摆的行是**直接**摆进 `d.rows` 的（见
// `setup`），所以队列文件里有没有东西跟这一档量到的东西无关。
//
// ⚠️ **`tasks` 要写成 `[]` 而不是 `null`**（票 #721 顺带修的一个夹具 bug）：
// `nil` 那个切片 marshal 出来是 **`null`**，而队列文件的读取（`service/download`
// 的 `decodeQueueFile`）**拒收 `tasks: null`**（它当成「文件里没有 tasks」）——
// 于是**挂下载就失败**，这一档压根没开始量。⇒ 写成**空数组**。
func budgetDownloadsMount() shellOpt {
	return mounted(func(t *testing.T, a *app.App) {
		dir := t.TempDir()
		qfile := filepath.Join(dir, download.QueueFileName)
		raw, err := json.Marshal(struct {
			Version int          `json:"version"`
			Tasks   []queuedTask `json:"tasks"`
		}{download.QueueVersion, []queuedTask{}})
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(qfile, raw, 0o644); err != nil {
			t.Fatal(err)
		}
		if err := a.MountDownloads(app.Downloads{
			Media: http.DefaultClient, QueueFile: qfile, FallbackDir: dlDir,
		}); err != nil {
			t.Fatalf("挂下载：%v", err)
		}
	})
}
