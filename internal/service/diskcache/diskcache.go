// Package diskcache 是**落盘缓存**公用下来的那几样东西。
//
// # 为什么单独一个包
//
// 仓库里有五处落盘缓存（弹幕、评论、歌词、封面、音频字节），而它们各自
// 抄了一份**一模一样**的「临时文件 → fsync → rename」原子写（见
// `service/danmaku`、`service/comments`、`service/lyrics`、`service/streamaudio`、
// `service/download` 各有一个 `writeAtomic`）。抄五份的代价是：
//
//  1. 改一处要改五处，而漏掉的那一处没人会发现（它只是「偶尔丢一次缓存」）；
//  2. 五份的细节**已经不一致了**——`download` 那份的临时文件前缀是
//     `.download-`，其余是各包自己的名字，而 `imgcache` 那份干脆**不 fsync**
//     （它只缓存图片，丢一次可以再下）。
//
// 而「过期」这一件事更糟：五处的过期基准**各不相同**，有的按「取回来的时刻」，
// 有的根本没有过期。于是「一份缓存多久算旧」在仓库里没有唯一答案。
//
// # 过期是**滚动**的
//
// 🔴 **判据是「最后一次用到的时刻」，不是「取回来的时刻」**。
//
// 用户的要求（2026-10-30）：
//
//	「过期7天应该会滚动刷新吧，比如第一天用户听的，应该第8天删；
//	  第三天用户又听了，这时候应该是第11天清的」
//
// 也就是说：**用户还在听的那一份，不该过期**。而按「取回来的时刻」算的话，
// 第一天下的歌，第七天就会从缓存里消失——哪怕用户这七天里天天在听它。
//
// ## 「最后用到」记在**文件的修改时刻**上
//
// 🔴 **不记在记录里面**。第一版是记在记录里（一个 `lastUsedAt` 栏），
// 而那一版有**三个真问题**（2026-10-30 的对抗性审查挖出来的）：
//
//  1. **读路径变成写路径**。要刷新那一栏，就得**把整份记录写回去**——
//     而那是一次「写 + fsync + rename + 目录 fsync」。于是「读一张封面」
//     变成了「读一张封面 + 刷一次盘」（实测 100 张从 5.8 毫秒涨到 858 毫秒）。
//  2. **丢更新**。读盘那一趟读到旧内容 → 期间网络那一趟写入了新内容 →
//     读的那一趟把整份旧记录写回去 ⇒ **新内容被旧内容盖掉**。症状是
//     「刚换的歌词源又变回旧的」。
//  3. **把用户自己的数据清掉**。歌词缓存里除了歌词文本还有**用户调过的
//     偏移和字号**——那两栏是用户数据，而「歌词文本过期了要重新拉一份」
//     不该顺手把它们清零。
//
// ⇒ 所以「最后用到」记在**文件系统那一侧**：文件本身的**修改时刻**（mtime）。
// 用到它的时候 `os.Chtimes` 把它推到当下——**只改元数据，不碰内容，
// 也不 fsync**：
//
//   - 不是写路径 ⇒ 读一张封面还是读一张封面（多一次系统调用而已）；
//   - 不碰内容 ⇒ **丢更新那一类问题整个不存在**；
//   - 不动用户数据 ⇒ 歌词文本过期时，用户调好的偏移和字号还在那份文件里。
//
// ## 为什么 mtime 也够用
//
// ⚠️ **mtime 会说谎**（用户改系统时间、备份工具还原文件、跨文件系统复制）。
// 而缓存的过期判据是「用户多久没用了」——那是一个**近似**就够了的事实：
// 差一天的后果是「缓存多留一天 / 早清一天」，而那两种后果用户都不会察觉。
//
// ⚠️ **对比一下另一个方案**（把时刻记在记录里，见上面那三条）——那三种
// 后果用户**会**察觉。
//
// ## 老缓存文件怎么办
//
// 老文件没有「最后用过」这一栏，而它们的 mtime 就是**当初写下去的时刻**——
// 那正好是「取回来的时刻」的上界。所以**老文件不需要任何迁移**：
// 它们按 mtime 判过期，和当初的行为一致。
//
// # 这一层不发请求
//
// 照 `service/danmaku` / `service/lyrics` 那一层的规矩：这一层只管读写盘，
// 取不取数据是调用方的事。
package diskcache

import (
	"os"
	"path/filepath"
	"runtime"
	"time"
)

// TTL 是内容缓存的默认有效期：7 天。
//
// 🔴 **它必须是同一个数**：弹幕、评论、歌词、封面、音频字节——五处各写一个
// 「7 天」的话，改一处就要改五处，而漏掉的那一处没人会发现。
//
// ⚠️ **评论缓存是另一档**（1 小时，见 `service/comments`）：评论会变，而歌词和
// 封面不会——那一档的差别是「内容本身会不会更新」，不是「缓存放多久」。
const TTL = 7 * 24 * time.Hour

// Fresh 报 path 那一份是不是还在有效期内。
//
// ⚠️ **判据是文件的修改时刻**（见文件头「最后用到记在文件的修改时刻上」）：
// 那就是「最后一次用到它」的时刻——每一次读到它都会把它推到当下。
//
// ⚠️ **「刚好满 TTL」算过期**（用的是 `<` 而不是 `<=`）：用户说的
// 「第一天用户听的，应该第 8 天删」——第一天 + 7 天 = 第 8 天，而那一天
// 它就该没了。
//
// ⚠️ **ttl <= 0 = 永不过期**（歌词缓存以前就是那一档：歌词不会变，
// 而「该更新了」对它没有意义）。
//
// ⚠️ **文件不在 / stat 失败 = 过期**：那一份根本没得用。
func Fresh(path string, now time.Time, ttl time.Duration) bool {
	if path == "" {
		return false
	}
	info, err := os.Stat(path)
	if err != nil {
		return false
	}
	if ttl <= 0 {
		// 永不过期，但**文件得在**——不然「永不过期」就变成了「永远有一份
		// 不存在的缓存」。
		return true
	}
	return now.Sub(info.ModTime()) < ttl
}

// Touch 把 path 那一份的「最后用过」推到 now。
//
// 🔴 **只改元数据，不碰内容**：改内容会有两个坏处——
//
//  1. 读路径变成写路径（一次 fsync + rename + 目录 fsync）；
//  2. 写回整份记录会把并发写进去的新内容盖成旧内容（丢更新）。
//
// ⇒ 用 `os.Chtimes`：一次系统调用，不碰内容，不 fsync。
//
// ⚠️ **失败不算错**：那只是这一次没记上「用过」，而下一次读还会再记。
// 缓存不该因为「记不上」就拒绝服务。
//
// ⚠️ **文件不在就什么都不做**（那一份已经没了）。
func Touch(path string, now time.Time) {
	if path == "" {
		return
	}
	_ = os.Chtimes(path, now, now)
}

// WriteAtomic 原子地把 b 写到 path：临时文件 → fsync → rename。
//
// ⚠️ **临时文件建在目标同一个目录里**：rename 只在同一文件系统内是原子的，
// 临时文件放到系统临时目录去的话，跨文件系统时 rename 会失败——而那正是
// 「用户把数据目录放在另一个盘上」的情形。
//
// ⚠️ **每一步失败都把临时文件删掉**：留着的话缓存目录里会攒出一堆
// 残骸（它们占地方，而用户看不出那是什么）。
func WriteAtomic(path string, b []byte) (err error) {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer func() {
		if err != nil {
			tmp.Close()
			os.Remove(name)
		}
	}()

	if _, err = tmp.Write(b); err != nil {
		return err
	}
	// 数据落盘了但目录项没有的话，断电之后可能还是旧文件。
	if err = tmp.Sync(); err != nil {
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	// CreateTemp 建出来的是 0600。缓存里没有隐私，给成普通用户文件同样的
	// 权限，不然用户从访达里看一眼缓存目录会以为坏了。
	if err = os.Chmod(name, 0o644); err != nil {
		return err
	}
	if err = os.Rename(name, path); err != nil {
		return err
	}
	return SyncDir(dir)
}

// SyncDir 把目录项本身刷到盘上。Windows 上打不开目录句柄，直接跳过——
// 那边 rename 本身就已经是原子的。
func SyncDir(dir string) error {
	if runtime.GOOS == "windows" {
		return nil
	}
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer d.Close()
	return d.Sync()
}
